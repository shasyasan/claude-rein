#!/usr/bin/env bash
# The command that writes the handover request marker. The session requesting a handover
# runs only this one script.
# The contract is docs/spec/handover.md. Letting each caller assemble the JSON from prose
# instructions would break the assumptions freshness validation depends on -- atomic writes,
# the time format, ordering against the canonical document -- differently for each writer, so
# this ships as a tool instead.
set -uo pipefail

# Normalizes the entry environment. Forces the character set to UTF-8 (bash can't parse
# this file's syntax under a non-UTF-8 multibyte locale) and unsets `CDPATH` (it makes
# `$(cd ... && pwd -P)` print two lines). Placed **before loading the shared library**. The
# canonical explanation lives next to the same two lines in bin/rein.
unset LC_ALL CDPATH
export LC_CTYPE=UTF-8

# Works out its own location with **string operations only** (dirname / basename are never
# started). Delegating that resolution to an external command means that whenever the command
# returns empty (a same-named command placed earlier on PATH), the destination collapses to
# empty and **the cwd gets grabbed as this file's own location** -- it would load and run
# lib/rein-common.sh out of whatever directory happened to be the working directory (start it
# from the directory where the trap was planted, and that file's contents run as-is -- observed).
# Since what gets loaded can be redirected from outside, this is closed off as an
# arbitrary-code-execution surface, not treated as merely the fixed cost of starting an
# external command.
# A launch given a relative path prefixes the cwd to make it absolute (the same shape as
# scripts/rein-hook.sh, scripts/rein-watcher.sh, and scripts/rein-seat.sh). Prefixing doesn't
# open the same trap -- at launch time the working directory hasn't moved yet, so the prefixed
# value is simply **wherever this file actually is**, with no room to collapse elsewhere the
# way the external-command failure above does by falling back to the working directory. This
# isn't rejected outright because launching with a relative path from inside the repository
# (typed next to `scripts/`, or as `scripts/rein-request.sh` from the repo root) is meant to be
# a legitimate way to run it.
SCRIPT_PATH="${BASH_SOURCE[0]}"
case "$SCRIPT_PATH" in
  /*) ;;
  *) SCRIPT_PATH="$PWD/$SCRIPT_PATH" ;;
esac
SCRIPT_DIR="${SCRIPT_PATH%/*}"
SCRIPT_NAME="${SCRIPT_PATH##*/}"
# shellcheck source-path=SCRIPTDIR
# shellcheck source=lib/rein-common.sh
. "$SCRIPT_DIR/lib/rein-common.sh"
# shellcheck source-path=SCRIPTDIR
# shellcheck source=lib/rein-config.sh
. "$SCRIPT_DIR/lib/rein-config.sh"

# The CLI's real path, embedded into the one-line hint. The rationale and how it's cut out
# live next to the same line in scripts/rein-seat.sh.
REIN_BIN="${SCRIPT_DIR%/*}/$REIN_CLI_RELPATH"

TARGET_CWD=""
RUNTIME_DIR_OPT=""
SESSION_ID=""
HANDOFF_OPT=""
SUCCESSOR_NAME=""
NOTE=""

RUNTIME_DIR=""
HANDOFF_PATH=""

usage() {
  cat <<EOF
usage: $SCRIPT_NAME --session-id <session ID> [--handoff <absolute path to the handoff document>] [options]
       $SCRIPT_NAME --selftest

  --session-id <id>       the ID of the session requesting the handover (required)
  --handoff <path>        the handoff document's path (relative resolves to absolute; if omitted, uses config's handoff_path, whose default is handoff.md next to the records)
  --cwd <path>            the target project directory (default: the current directory)
  --runtime-dir <path>    where runtime data is kept (default: config's runtime_dir, falling back to XDG's state area)
  --successor-name <name> the successor session's display name (generated by the watcher if omitted)
  --note <text>           a note for you to read later (not used in any decision)
EOF
}

fail() {
  printf '%s: %s\n' "$SCRIPT_NAME" "$1" >&2
  return 1
}

# Checks a CLI flag's value (the wording of the reason lives in the config layer -- not
# rewritten separately in each of the 3 scripts).
check_opt() {
  rein_config_check_opt "$@" && return 0
  printf '%s: %s\n' "$SCRIPT_NAME" "$REIN_CONFIG_ERROR" >&2
  return 2
}

# Checks the value of a flag that has no config key. The same discipline as the side that does
# have one (check_opt) applies here too -- silently falling through to a failed `shift 2` would
# end non-zero **without printing a single line of reason** (a handover request is one line the
# primary session fires automatically, so a silent non-zero means the handover simply never
# happens with nobody able to observe why; skills/request/SKILL.md promises 'the reason goes to
# stderr'). An explicit empty value isn't folded into unset either (`--cwd ""` grabs the shell's
# own current lineage instead of the intended target, and `--note ""` silently drops a note the
# caller meant to write -- both would otherwise pass through as a different input with no signal
# at all). The wording matches bin/rein's need_value exactly (the same situation isn't said two
# different ways).
need_value() {
  local flag="$1" count="$2" value="${3-}"
  if [ "$count" -lt 2 ]; then
    fail "${flag} requires a value"
    return 2
  fi
  if [ -z "$value" ]; then
    fail "${flag} cannot take an empty value (not treated as unspecified)"
    return 2
  fi
  return 0
}

# Turns a relative path into an absolute one (with symlinks resolved). A parent that doesn't
# exist fails as unresolvable. Cutting out the parent and the name uses **shell string
# operations only** (dirname / basename are never started). Using an external command's output
# directly as the destination means that whenever that command returns empty or `.` -- a
# same-named command placed earlier on PATH -- the parent collapses to the caller's cwd, and
# `--handoff sub/handoff.md` **silently grabs a different `./handoff.md` than what was
# specified** (observed: with decoys laid out, the return value pointed at a decoy and not one
# line of signal came out). What gets passed here is 'which document to hand off' -- the one
# file the successor reads -- so no run that collapsed onto a different file is ever let
# through silently.
resolve_abs_path() {
  local path="$1" dir
  case "$path" in
    /*) ;;
    *) path="$PWD/$path" ;;
  esac
  # Only right under the filesystem root (`/handoff.md`) does the cut produce an empty string.
  # Passing that empty value through would let `cd ""` **succeed without changing the working
  # directory**, producing the same 'collapses onto the cwd' shape as above -- so name the root
  # explicitly instead.
  dir="${path%/*}"
  [ -n "$dir" ] || dir="/"
  dir="$(cd "$dir" 2>/dev/null && pwd -P)"
  if [ -z "$dir" ]; then
    return 1
  fi
  printf '%s/%s\n' "$dir" "${path##*/}"
}

# Reads the config layer, layers the CLI flags on top (stronger than environment variables),
# and then extracts the effective values. A handover request is a one-shot command, so this is
# only ever read once, at invocation.
load_config() {
  if ! rein_config_prepare "$REIN_BIN" "$TARGET_CWD"; then
    fail "$REIN_CONFIG_ERROR"
    return 1
  fi
  # CLI flags are layered on top of the config layer (type and absolute-path checks aren't
  # rewritten separately in each of the 3 scripts).
  if [ -n "$RUNTIME_DIR_OPT" ] && ! rein_config_override runtime_dir "$RUNTIME_DIR_OPT"; then
    fail "$REIN_CONFIG_ERROR"
    return 1
  fi
  if [ -n "$HANDOFF_OPT" ]; then
    HANDOFF_PATH="$(resolve_abs_path "$HANDOFF_OPT")"
    if [ -z "$HANDOFF_PATH" ]; then
      fail "cannot resolve the handoff document's path: ${HANDOFF_OPT}"
      return 1
    fi
    if ! rein_config_override handoff_path "$HANDOFF_PATH"; then
      fail "$REIN_CONFIG_ERROR"
      return 1
    fi
  fi
  if ! rein_config_check_cross_fields; then
    fail "$REIN_CONFIG_ERROR"
    return 1
  fi
  rein_config_bind HANDOFF_PATH handoff_path || return 1
  rein_config_bind RUNTIME_DIR runtime_dir || return 1
  RUNTIME_DIR="$(rein_resolve_runtime_dir "$TARGET_CWD" "$RUNTIME_DIR")"
  if [ -z "$RUNTIME_DIR" ]; then
    fail "cannot resolve where runtime data is kept (set it explicitly with --runtime-dir)"
    return 1
  fi
  # The gate that only a selftest child hits (isolation breaking dies right here, the moment
  # it breaks). **The same predicate, the same role** as hook_prepare in rein-hook.sh and
  # prepare_runtime in lib/cli/base.sh. 'Stop before writing' only holds at this one position,
  # where every location is resolved and not one byte has been written yet.
  # A handover request writes to exactly 2 places: (a) the runtime directory (the operation
  # lock, the marker) and (b) the handoff document (the touch right before publishing). Both
  # are derived from the values this function just resolved, so even if more writes get added
  # later, this one spot still covers them (**don't add a check per write site** -- the one you
  # forget to add becomes the hole).
  # **Not split into stages, because no path writes anything before this function runs** -- a
  # missing prerequisite tool, a malformed session_id, or a cwd that fails to resolve all end in
  # stderr and a GUI notification only, never on disk (the watcher needing two of these, one for
  # the records branch and one for the runtime-data branch, is because its failure paths before
  # this point do write to wlog).
  # The records location itself isn't passed in -- a handover request never writes a single byte
  # to the records (only `watcher_start_hint` reads it). The default handoff_path sits next to
  # the records (`<records>/handoff.md`), so isolation breaking on the records side is still
  # caught through the handoff document's own path.
  # The gate to fail through is `fail` (one line to stderr) -- the rejecting side never writes
  # a single byte under the never-touch root.
  if [ -n "${REIN_SELFTEST_NEVER_ROOTS:-}" ] &&
    rein_selftest_never_root_hit "$RUNTIME_DIR" "$HANDOFF_PATH"; then
    fail "a selftest child resolved a location it must never touch (isolation is broken): ${REIN_SELFTEST_NEVER_ROOT_HIT}"
    return 1
  fi
  return 0
}

# The hint for how to start the watcher. **Emits a line that runs even for a lineage with
# explicit locations** -- a prose aside like 'add the same `--cwd` / `--root` / `--runtime-dir`'
# makes the user go look the effective values up themselves, and getting one wrong starts a
# watcher looking at a different location (which starts fine, but never picks up this request).
# The lineage is named through the one helper every writer of a hint goes through.
watcher_start_hint() {
  local records
  # The records location is only used as material for deciding whether the lineage should be
  # named through `--root`. This whole function isn't failed when it can't be resolved (the
  # location is a symlink) -- this is the side that hands out **how to fix a request that
  # already failed**, and whether the location itself is sound is checked separately by the
  # side that writes to the records.
  # **But empty is never passed through as 'the default lineage'** -- carrying an empty value
  # forward would emit a `--runtime-dir` line, and for a lineage relocated to a root, that
  # **starts a watcher looking at a different location** (the records fall back to
  # `<cwd>/.rein/`, and this request goes on sitting unpicked). Say 'cannot tell' when it can't
  # be told.
  # Resolution is called outside `$( )` -- the failure reason (REIN_RECORDS_ERROR) doesn't stay
  # closed inside a subshell and can be carried straight into this hint (the value itself
  # arrives through REIN_RECORDS_PATH).
  if rein_records_dir "$TARGET_CWD" >/dev/null 2>&1; then
    records="$REIN_RECORDS_PATH"
  else
    records=""
  fi
  if ! rein_lineage_cmd "$REIN_BIN" "$RUNTIME_DIR" "$records" "$TARGET_CWD" up; then
    printf 'start the watcher first (%s: %s. Check the effective values for this lineage before starting it)' \
      "$REIN_LINEAGE_ERROR" "${REIN_RECORDS_ERROR:-cannot resolve the records location}"
    return 0
  fi
  printf 'start the watcher first: %s' "$REIN_LINEAGE_CMD"
}

# How to fix a lineage that explicitly emptied out `handoff_path`. **Fills in effective values
# for both the lineage (`--root` / `--config`) and the scope (`--user` / `--project`)** -- drop
# the scope and `config unset`'s default (project) takes over, so an empty value placed at the
# user layer keeps failing with the same reason even after running the hint exactly as given
# (reproduced by observation). When either one can't be determined, **no line to run is
# emitted** -- this returns what couldn't be determined instead (the same discipline used for
# naming the lineage above).
# The message is assembled into a variable. The line to run is placed **at the end of the
# line** so the hint can be selected straight off the terminal and pasted (no trailing
# punctuation or parenthesis after it).
HANDOFF_EMPTY_HINT=""
handoff_empty_hint() {
  local scope
  if ! rein_config_scope_opt handoff_path; then
    printf -v HANDOFF_EMPTY_HINT 'to fall back to the default, fix whichever layer you emptied it at (%s)' \
      "$REIN_CONFIG_SCOPE_ERROR"
    return 2
  fi
  scope="$REIN_CONFIG_SCOPE_OPT"
  if ! rein_config_lineage_cmd "$REIN_BIN" "$REIN_CONFIG_USER_FILE" "$TARGET_CWD" \
    "unset${scope} handoff_path"; then
    printf -v HANDOFF_EMPTY_HINT 'reset handoff_path to the default in the config for this lineage (%s)' \
      "$REIN_LINEAGE_ERROR"
    return 2
  fi
  printf -v HANDOFF_EMPTY_HINT 'to fall back to the default, run this: %s' "$REIN_LINEAGE_CMD"
}

run_request() {
  local marker_file reason rc resolved_cwd cwd_error

  # Writing while a tool is missing would leave behind an out-of-contract time format or broken
  # JSON, which the watcher would reject with the wrong reason (R1/R4). Fail on the writer's
  # side first instead.
  if ! rein_check_prerequisites "$SCRIPT_PATH"; then
    printf -v reason 'a prerequisite tool is not usable: %s' "$REIN_MISSING_TOOLS"
    fail "$reason"
    rein_notify "rein: cannot write the handover request" "$reason"
    return 2
  fi

  if [ -z "$SESSION_ID" ]; then
    fail "--session-id is required"
    return 2
  fi
  # Shape checking goes through one shared-library function (the same one the hook's stdin and
  # the watcher's R3 use). Letting a path separator through would let the reader write outside
  # its own location when it rotates the marker aside.
  if ! rein_session_id_shape_ok "$SESSION_ID" "--session-id"; then
    fail "$REIN_SESSION_ID_ERROR"
    return 2
  fi

  if [ -z "$TARGET_CWD" ]; then
    TARGET_CWD="$PWD"
  fi
  if [ ! -d "$TARGET_CWD" ]; then
    fail "the target directory doesn't exist: ${TARGET_CWD}"
    return 2
  fi
  # A directory that exists but can't be resolved (no permission to cd into it, an unreadable
  # parent) still happens, so the resolution failure is checked. Skipping the check would carry
  # an empty cwd forward, turn the failure reason into something unrelated (the runtime
  # directory's owner, the watcher being undecidable), and leak bash's raw error line into
  # user-facing output. The reason swallows cd's own stderr and folds it into this one line (the
  # same wording as the same resolution in bin/rein).
  resolved_cwd="$(cd "$TARGET_CWD" 2>/dev/null && pwd -P)"
  if [ -z "$resolved_cwd" ]; then
    # **Expected to fail here** (this only fetches the text of the reason), so the exit code
    # isn't checked.
    cwd_error="$(cd "$TARGET_CWD" 2>&1 || :)"
    # Drop bash's own prefix (`<script>: line <n>: cd: `) and keep only the reason.
    case "$cwd_error" in
      *": cd: "*) cwd_error="${cwd_error##*": cd: "}" ;;
    esac
    fail "cannot resolve the target directory: ${cwd_error:-$TARGET_CWD}"
    return 2
  fi
  TARGET_CWD="$resolved_cwd"

  load_config || return 1

  # The handoff document's location has a default (next to the records, where `rein init`
  # places the template). It comes back empty only for a lineage that **explicitly** emptied out
  # config's `handoff_path`, and in that case this fails rather than guessing its way back to
  # the default -- it never writes 'a handover request with no handoff document'.
  # The line to fix it fills in effective values for **both the lineage and the scope** (missing
  # either one means the pasted line either edits a different config or leaves the value in
  # place, failing with the same reason forever).
  if [ -z "$HANDOFF_PATH" ]; then
    handoff_empty_hint
    fail "the handoff document's path could not be determined (config's handoff_path is explicitly empty). Pass one with --handoff, or ${HANDOFF_EMPTY_HINT}"
    return 2
  fi
  # Acceptance conditions (a regular file, not a symlink, non-empty) go through one
  # shared-library function -- so only the shape a cold start (rein init's template) and the
  # first session's launch (bootstrap) already accept is treated as canonical here too.
  if ! rein_handoff_file_ok "$HANDOFF_PATH"; then
    fail "$REIN_HANDOFF_ERROR"
    return 1
  fi
  # Checking the section structure is something **only a handover request** enforces (a
  # different function from the acceptance check above -- placing the template and launching the
  # first session only use the boolean, and gating those on sections too would leave a lineage
  # unable to start before the template is even placed). It's stopped here because a section
  # that accumulates gets copied forward at every handover and never goes away without someone
  # removing it by hand.
  if ! rein_handoff_sections_ok "$HANDOFF_PATH"; then
    fail "$REIN_HANDOFF_SECTION_ERROR"
    return 1
  fi

  marker_file="$RUNTIME_DIR/$REIN_MARKER_BASENAME"
  # Verifying the owner (read-only) comes first. Doing it later would mean a request that ended
  # up pointing at a different lineage's location fails with 'there is an unconsumed handover
  # request marker' instead of 'wrong owner' -- making it look to the user as if an old
  # request is stuck in their own lineage, steering them toward deleting the existing marker
  # (a contract violation).
  if ! rein_verify_runtime_owner "$RUNTIME_DIR" "$TARGET_CWD"; then
    fail "$REIN_RUNTIME_ERROR"
    return 1
  fi
  # Checking residency comes **after** verifying the owner and **before** the unconsumed-marker
  # check (docs/spec/handover.md). This one here is **an early courtesy** -- checked once more
  # before taking mutual exclusion, so that even a lineage whose location doesn't exist yet
  # (one that can't even set up an operation lock) still gets a 'start the watcher first' line.
  require_watcher_present || return 1
  # Running children are checked **after** residency: a lineage with no watcher can't hand over
  # at all, and that is the reason worth putting in front of the user first (a running child is a
  # state that clears itself within minutes; a missing watcher is a setup problem that doesn't).
  require_no_live_children || return 1
  # The check for an unconsumed marker and the publish itself happen inside one mutually
  # exclusive region (publish_marker below). Splitting them means two requests fired at the same
  # time can **both** read 'none unconsumed' and the one that writes second overwrites the
  # first -- the loser's request disappears with no non-zero exit and no record at all (observed:
  # both exited 0 in 10 out of 10 runs).
  claim_publish_lock || return 1
  # **The judgment that decides whether to publish runs once, inside this exclusive region.**
  # Publishing on the strength of the outer judgment alone means that on a run that races `down`
  # (which takes the same operation lock, then stops the watcher before releasing it), a stale
  # 'it's there' judgment carries all the way to placing the marker at a location with no watcher
  # left, reporting success with 0 -- the requester believes it landed and stays quiet, while
  # nobody is there to pick it up.
  require_watcher_present
  rc=$?
  if [ "$rc" -eq 0 ]; then
    publish_marker "$marker_file"
    rc=$?
  fi
  release_publish_lock
  return "$rc"
}

# Placing a marker at a location with no watcher leaves the request stuck with nobody there to
# remove it (no handover happens on that lineage until the user next starts the watcher).
# This one function is the only place that decides, and both the check outside the publish's
# exclusive region (an early courtesy) and the one inside it (whether to publish) go through it.
# 0=running / 1=don't place it (the reason has already gone to stderr and the notification)
require_watcher_present() {
  local reason rc
  rein_watcher_state "$RUNTIME_DIR" "$TARGET_CWD"
  rc=$?
  if [ "$rc" -eq 1 ]; then
    printf -v reason 'the watcher is not running, so no handover request will be placed (%s). %s' \
      "$REIN_WATCHER_REASON" "$(watcher_start_hint)"
    fail "$reason"
    rein_notify "rein: cannot write the handover request" "$reason"
    return 1
  fi
  # Undecidable (the watcher lock's owner can't be read, or isn't numeric -- there simply isn't
  # enough material to judge at all) is never flattened into a flat 'not running'. Falling back
  # to the start-it hint would actually start a second watcher on a lineage that's already being
  # watched. A case where the binary itself could be cross-checked (a PID reuse) never reaches
  # this branch -- that's handled by the 'not running' branch above.
  if [ "$rc" -ne 0 ]; then
    printf -v reason 'cannot tell whether the watcher is running, so no handover request will be placed (%s). Check who owns the watcher lock %s' \
      "$REIN_WATCHER_REASON" "$RUNTIME_DIR/$REIN_LOCK_DIRNAME"
    fail "$reason"
    rein_notify "rein: cannot write the handover request" "$reason"
    return 1
  fi
  return 0
}

# Refuse the request while this session still has a running child (subagent).
#
# **A handover replaces the primary session, and a child dies with its parent.** The invariant
# "never hand over while a child is alive" was already written down, and the Stop push already
# defers on it -- but the push is only one of the two ways a request gets placed. Typing the
# command reached this side, which had no view of children at all, so a handover requested by
# hand went straight through (observed: of 3 children running, 2 ended having written nothing).
#
# **The evidence is the ledger the hooks keep** (`<runtime>/children/<session_id>.<agent_id>`),
# because a payload -- the hooks' own evidence -- never reaches this process. Only this session's
# own entries are read: leftovers from earlier generations exist by design (a session stopped
# externally never delivers SubagentStop), and reading them would refuse a handover forever.
#
# **The ledger is the primary evidence and the record's mtime is only the expiry cutoff**, the
# same two-layer judgment the hooks use. An entry whose child has gone quiet past the cutoff is
# not counted -- otherwise a child that vanished without its SubagentStop (its parent killed, the
# session crashed) would block that session's handover permanently. Where the record file isn't
# there yet, the moment of registration stands in for it, so a child registered seconds ago is
# never read as expired.
#
# **There is no escape hatch on purpose.** A `--force` would place the marker, the watcher would
# replace this session, and the children would die anyway -- nothing is rescued by overriding it.
# 0 = no running children / 1 = refuse (the reason has already gone to stderr)
require_no_live_children() {
  local dir file name agent_id agent_type started record mtime latest age now count=0 detail="" reason
  dir="$RUNTIME_DIR/$REIN_CHILDREN_DIRNAME"
  [ -d "$dir" ] || return 0
  now="$(rein_now_epoch)"
  # Selected by **building the prefix out of this session's own id**, never by splitting a name on
  # `.` -- a session_id may legitimately contain one (only a path separator and whitespace are
  # rejected), so splitting would attribute another session's entry to this one.
  # **The prefix stays inside the quotes, and only the trailing `*` is left as a pattern.** A
  # session_id can carry `[`, `?` or `*` as well (nothing rejects those either); quoted, they are
  # matched literally, while the same word unquoted would read them as pattern characters and
  # match none of that session's own entries -- reopening this hole for exactly those sessions.
  for file in "$dir/$SESSION_ID."*; do
    [ -f "$file" ] || continue
    name="${file##*/}"
    agent_type=""
    started=""
    record=""
    {
      IFS= read -r agent_type
      IFS= read -r started
      IFS= read -r record
    } <"$file" 2>/dev/null || :
    latest="$started"
    if [ -n "$record" ] && [ -f "$record" ]; then
      mtime="$(rein_mtime "$record")"
      case "$mtime" in
        '' | *[!0-9]*) ;;
        *)
          case "$latest" in
            '' | *[!0-9]*) latest="$mtime" ;;
            *) if [ "$mtime" -gt "$latest" ]; then latest="$mtime"; fi ;;
          esac
          ;;
      esac
    fi
    rein_child_active_at "$latest" "$now" || continue
    count=$((count + 1))
    agent_id="${name#"$SESSION_ID".}"
    # A ledger entry whose start time is unreadable still counts as a running child -- what it
    # can't say is *how long*, and saying "unrecorded" is never collapsed into a number.
    case "$started" in
      '' | *[!0-9]*) age="its start time is not recorded" ;;
      *) age="running for $((now - started)) seconds" ;;
    esac
    printf -v detail '%s%s%s (agent %s, %s)' \
      "$detail" "${detail:+, }" "${agent_type:-unknown}" "$agent_id" "$age"
  done
  [ "$count" -gt 0 ] || return 0
  printf -v reason 'this session still has %s running child agent(s), so no handover request will be placed (a handover replaces this session, and its children die with it): %s. Let them finish, then run this again' \
    "$count" "$detail"
  fail "$reason"
  return 1
}

# The publish's mutual exclusion is **the existing operation lock** (the same one `up` / `down`
# already take). Publishing a request writes only after checking whether the watcher is there,
# so it's correct not to let it interleave with starting or stopping the watcher. Adding a new
# lock location would grow the runtime directory with an item that cleanup (prune) and
# diagnostics (doctor) don't know about.
# It waits so that the loser falls through **the existing 'there is an unconsumed handover
# request marker' non-zero path** -- failing immediately here instead would give two different
# outcomes, with two different reasons, to what looks to the user like the same event (a
# request already sitting there).
PUBLISH_LOCK_DIR=""
PUBLISH_LOCK_TOKEN=""
PUBLISH_LOCK_TRIES=100
PUBLISH_LOCK_WAIT_SEC=0.05
claim_publish_lock() {
  local lock="$RUNTIME_DIR/$REIN_OP_LOCK_DIRNAME" tries=0 rc owner
  PUBLISH_LOCK_DIR=""
  PUBLISH_LOCK_TOKEN="$(rein_nonce)"
  while :; do
    # The discipline for reclaiming also goes through one shared-library function (so a lock
    # whose owner is gone never permanently blocks the handover gate for a lineage).
    rein_claim_lock_dir_or_reclaim "$lock" \
      start "$(rein_process_start_identity "$$")" \
      cwd "$TARGET_CWD" \
      mode "$REIN_LOCK_MODE_OP" \
      token "$PUBLISH_LOCK_TOKEN"
    rc=$?
    if [ "$rc" -eq 0 ]; then
      PUBLISH_LOCK_DIR="$lock"
      return 0
    fi
    if [ "$rc" -eq 1 ]; then
      fail "cannot set up the operation lock: ${lock}"
      return 1
    fi
    tries=$((tries + 1))
    if [ "$tries" -ge "$PUBLISH_LOCK_TRIES" ]; then
      owner="$(rein_lock_pid "$lock")"
      fail "another rein operation is in progress (pid=${owner:-unknown}): ${lock}"
      return 1
    fi
    sleep "$PUBLISH_LOCK_WAIT_SEC"
  done
}

release_publish_lock() {
  local rc
  [ -n "$PUBLISH_LOCK_DIR" ] || return 0
  # Only releases the lock if it's still its own generation (token check). A 2 means 'another
  # rein already reclaimed it' -- correctly backing off, not a mechanism failure to raise an
  # alarm about.
  rein_release_lock_dir_if_mine "$PUBLISH_LOCK_DIR" "$PUBLISH_LOCK_TOKEN"
  rc=$?
  if [ "$rc" -eq 1 ]; then
    printf '%s: cannot release the operation lock (confirm no other rein is running here, then rmdir %s)\n' \
      "$SCRIPT_NAME" "$(rein_shell_quote "$PUBLISH_LOCK_DIR")" >&2
  fi
  PUBLISH_LOCK_DIR=""
  return 0
}

# Check for an unconsumed marker -> touch the handoff document -> publish the marker. The
# caller holds the publish's mutual exclusion when calling this.
# Drops the handover signals this session itself placed (the signal that its response has
# finished, and the cancellation signal). Their contents are one line, the session_id; anything
# that doesn't match belongs to a different session and is left alone. Publishing doesn't
# proceed if one can't be removed (a leftover cancellation signal would erase the next handover
# on the first pass of its wait loop -- letting that pass silently leads straight to a false
# cancellation).
drop_own_handover_marks() {
  local name file line
  for name in "$REIN_HANDOVER_READY_BASENAME" "$REIN_HANDOVER_CANCEL_BASENAME"; do
    file="$RUNTIME_DIR/$name"
    [ -f "$file" ] || continue
    line=""
    IFS= read -r line <"$file" 2>/dev/null || line=""
    [ "$line" = "$SESSION_ID" ] || continue
    if ! rm -f "$file"; then
      fail "cannot remove the previous handover signal (leaving it cancels the next handover): ${file}"
      return 1
    fi
  done
  return 0
}

publish_marker() {
  local marker_file="$1" requested_at marker_json rc
  if [ -e "$marker_file" ]; then
    fail "there is an unconsumed handover request marker (won't overwrite it until the watcher processes it): ${marker_file}"
    return 1
  fi
  # Creation (the owner's write) happens after the judgment.
  rein_ensure_runtime_dir "$RUNTIME_DIR" "$TARGET_CWD"
  rc=$?
  if [ "$rc" -ne 0 ]; then
    fail "$REIN_RUNTIME_ERROR"
    return 1
  fi

  # The tool guarantees the handoff-document-before-marker order (R7 checks that the document
  # wasn't left stale before the marker). This touch, not a window value, is what closes off the
  # gap where the document could go stale for however long verification takes.
  if ! touch "$HANDOFF_PATH"; then
    fail "cannot update the handoff document's mtime: ${HANDOFF_PATH}"
    return 1
  fi
  requested_at="$(rein_iso_now)"

  # Writes only **what the request side actually knows**. The marker can carry one more field,
  # `launch_attempt` (the successor the watcher started on that attempt), but that's **a field
  # the reader (the watcher) fills in after accepting the request** -- the request side never
  # writes it. Starting the successor and updating the current pointer aren't atomic, so if the
  # watcher dies in between, the watcher itself is what's left to tell 'started it but the
  # pointer has nowhere to land' apart from 'never started it at all'. Writing this field here
  # first would let a watcher that comes back set the requester's claimed session as the primary
  # session.
  marker_json="$(jq -nc \
    --arg schema "$REIN_MARKER_SCHEMA" \
    --arg session_id "$SESSION_ID" \
    --arg requested_at "$requested_at" \
    --arg handoff_path "$HANDOFF_PATH" \
    --arg cwd "$TARGET_CWD" \
    --arg successor_name "$SUCCESSOR_NAME" \
    --arg note "$NOTE" \
    '{
      schema: $schema,
      session_id: $session_id,
      requested_at: $requested_at,
      handoff_path: $handoff_path,
      cwd: $cwd
    }
    + (if $successor_name == "" then {} else {successor_name: $successor_name} end)
    + (if $note == "" then {} else {note: $note} end)')"
  if [ -z "$marker_json" ]; then
    fail "cannot generate the marker's JSON (jq is not usable)"
    return 1
  fi

  # **Drops its own two signals before publishing.** If the user speaks up in the window
  # between exiting the wait loop and the pointer moving to the successor, a cancellation
  # signal gets placed even though nobody is left to read it (the only point of consumption is
  # at the tail of the watcher's own wait loop). Leaving it there would then match on the first
  # pass of the wait loop the next time the same session re-issues the same request (stranded
  # in processing/ by a failed step, recovered on the next launch, re-requested), **producing
  # a 'cancelled because you spoke up' notification even though the user never spoke up**.
  # The cleanup isn't placed at the entry of the wait loop, because that would also throw away a
  # legitimate cancellation placed before the claim -- the declaration 'I want to hand over now'
  # is meant to invalidate past cancellations, not future ones.
  # Only drops signals whose contents are its own session_id (another session's signals are
  # left untouched).
  if ! drop_own_handover_marks; then
    return 1
  fi

  if ! rein_write_json_atomic "$marker_file" "$marker_json"; then
    fail "cannot write the marker: ${marker_file}"
    return 1
  fi

  printf '%s: placed a handover request: %s\n' "$SCRIPT_NAME" "$marker_file"
  return 0
}

