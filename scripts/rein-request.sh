st_setup_case() {
  local case_dir="$1"
  mkdir -p "$case_dir"
  ST_CWD="$(cd "$case_dir" && pwd -P)"
  ST_RUNTIME="$ST_CWD/runtime"
  ST_HANDOFF="$ST_CWD/handoff.md"
  # The document for cases meant to pass matches **the template's section structure exactly**
  # (a handover request rejects both a missing section and a heading not in the template).
  # Assembly happens in one place in fixtures, from the section ordering -- section names are
  # never copied out by hand here.
  rein_st_write_handoff "$ST_HANDOFF"
  ST_MARKER="$ST_RUNTIME/$REIN_MARKER_BASENAME"
  # Now that this reads the config layer, checks must always point at an isolated config (in an
  # environment with a real config present, its values would move the check's effective values).
  ST_USER_CONFIG="$ST_CWD/user-config"
  # Rather than write out env per entry point, isolation is assembled in one place in fixtures
  # (leaving even one path that forgets to drop the surrounding REIN_* lets the user's real
  # config move the check's outcome).
  rein_st_isolation_env "$ST_USER_CONFIG" "$ST_CWD/xdg-config" "$ST_CWD/xdg-state"
  ST_ENV_ARGS=("${REIN_ST_ENV_ARGS[@]}")
  # A handover request can only be written on a lineage with a watcher present -- so cases
  # meant to pass default to it running. Only the cases that measure the not-running shape opt
  # out, with rein_st_stop_fake_watcher.
  rein_st_start_fake_watcher "$ST_RUNTIME" "$ST_CWD"
}

# The default entry point suppresses GUI notifications (a case that goes through it doesn't
# place a fake osascript, so without suppression the check would pop a real notification on the
# user's screen). A case that inspects the notification itself builds its own dedicated launch
# with a fake osascript on PATH instead -- it doesn't suppress.
st_run_request() {
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 "$REIN_ST_BASH" "$SCRIPT_PATH" "$@" 2>&1 </dev/null)"
  ST_STATUS=$?
}

st_expect_status() {
  local name="$1" expected="$2"
  if [ "$ST_STATUS" -ne "$expected" ]; then
    st_fail "${name}" "exit=${ST_STATUS} (expected ${expected}): ${ST_OUT}"
    return 1
  fi
  return 0
}

# The rejecting side is checked on all 3 points together: non-zero, a reason on stderr, and
# marker written.
# A call whose expected string is empty **always matches** (`*""*` matches any string) -- that
# would bank a pass without ever looking at the output. A call that passes the whole needle
# through a variable does exist, so a typo in that variable's name would turn 'green' by
# accident. An empty needle is failed as a broken check instead.
st_reject_case() {
  local name="$1" expected="$2" needle="$3"
  if [ -z "$needle" ]; then
    st_fail "${name}" "the expected string is empty (a broken check -- passes without looking at the output)"
    return
  fi
  if ! st_expect_status "${name}" "$expected"; then
    return
  fi
  case "$ST_OUT" in
    *"$needle"*) ;;
    *)
      st_fail "${name}" "the reason doesn't contain ${needle}: ${ST_OUT}"
      return
      ;;
  esac
  if [ -f "$ST_MARKER" ]; then
    st_fail "${name}" "wrote a marker for input meant to fail"
    return
  fi
  st_ok
}

# Cuts out the one line of hint (from after `start the watcher first: ` to the end of the line)
# and checks it by **exact match**. A partial match (`*"..."*`) would let a flat claim that
# dropped the lineage name through on nothing more than a matching prefix.
ST_HINT_LEAD='start the watcher first: '
st_expect_hint_line() {
  local name="$1" expected="$2" line
  case "$ST_OUT" in
    *"$ST_HINT_LEAD"*) ;;
    *)
      st_fail "${name}" "cannot cut out the hint line (no ${ST_HINT_LEAD}): ${ST_OUT}"
      return
      ;;
  esac
  line="${ST_OUT#*"$ST_HINT_LEAD"}"
  line="${line%%$'\n'*}"
  if [ "$line" = "$expected" ]; then
    st_ok
  else
    st_fail "${name}" "the hint line is wrong: [${line}] / expected [${expected}]"
  fi
}

# The text placed right before the fix-it hint (the line to run is placed **at the end of the
# line** so it can be selected off the terminal and pasted).
ST_HINT_LEAD_HANDOFF='to fall back to the default, run this: '

# Keeps the cutting-out logic in one place (pulled from **the output itself** -- never measured
# against text the check reassembled on its own).
# 0=cut out successfully (ST_HINT_LINE) / 1=the lead text isn't in the output
ST_HINT_LINE=""
st_cut_hint_line() {
  local lead="$1" line
  ST_HINT_LINE=""
  case "$ST_OUT" in
    *"$lead"*) ;;
    *) return 1 ;;
  esac
  line="${ST_OUT#*"$lead"}"
  ST_HINT_LINE="${line%%$'\n'*}"
}

# The same cutting-out as above, given the lead text to look for, checked by **exact match**.
st_expect_hint_line_after() {
  local lead="$1" name="$2" expected="$3"
  if ! st_cut_hint_line "$lead"; then
    st_fail "${name}" "cannot cut out the hint line (no ${lead}): ${ST_OUT}"
    return
  fi
  if [ "$ST_HINT_LINE" = "$expected" ]; then
    st_ok
  else
    st_fail "${name}" "the hint line is wrong: [${ST_HINT_LINE}] / expected [${expected}]"
  fi
}

# **Cuts the hint line out of the output and runs it exactly as-is.** Matching the text alone
# can't measure whether the line actually runs and works -- a line that dropped a scope or a
# lineage would still match right up to the end as text.
# Runs it the same way a user would: puts `rein` on PATH and hands the shell one line
# (`bash -c`). If the check re-split it into arguments instead, a hint with broken quoting would
# pass on 'the correct argv on the re-split side.'
# The isolation env is layered on as-is (a `--config` / `--root` the hint names still points at
# the same location under this env -- that's part of what makes the hint correct).
st_run_hint_line() {
  local name="$1" lead="$2" bin_dir
  if ! st_cut_hint_line "$lead"; then
    st_fail "${name}" "cannot cut out the hint line (no ${lead}): ${ST_OUT}"
    return 1
  fi
  bin_dir="$ST_CWD/hint-bin"
  mkdir -p "$bin_dir"
  ln -sf "$(cd "$SCRIPT_DIR/.." && pwd -P)/bin/rein" "$bin_dir/rein"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 PATH="$bin_dir:$PATH" \
    "$REIN_ST_BASH" -c "$ST_HINT_LINE" 2>&1 </dev/null)"
  ST_STATUS=$?
  if [ "$ST_STATUS" -eq 0 ]; then
    st_ok
    return 0
  fi
  st_fail "${name}" "the hint line exited ${ST_STATUS}: ${ST_OUT}"
  return 1
}

# Checks that a bare form with no lineage named appears **nowhere in the output**. Looks right
# after every occurrence of $2 and counts as a violation any occurrence not immediately followed
# by $3 -- not a single check at the end of the line, which would let a bare form mixed into
# prose pass through unnoticed.
st_expect_no_bare_hint() {
  local name="$1" needle="$2" required_next="$3" rest="$ST_OUT" bare=0
  while :; do
    case "$rest" in
      *"$needle"*) ;;
      *) break ;;
    esac
    rest="${rest#*"$needle"}"
    case "$rest" in
      "$required_next"*) ;;
      *) bare=$((bare + 1)) ;;
    esac
  done
  if [ "$bare" -eq 0 ]; then
    st_ok
  else
    st_fail "${name}" "${bare} occurrence(s) with no lineage named (not followed by ${required_next}): ${ST_OUT}"
  fi
}

# Fires two requests (with different content) at the same time and measures what comes out. If
# checking for an unconsumed marker and publishing aren't inside one exclusive region, both
# read 'none unconsumed' and **both exit 0** -- the loser's request disappears with no non-zero
# exit and no record at all. A single observation can't be told apart from a run that happened
# to serialize by chance, so this repeats it (the winner changes run to run).
# The same barrier also measures the published artifact's own non-regression (always complete
# JSON, no leftover temp file) at the same time.
st_two_writer_barrier_case() {
  local runs="$1" i pid_a pid_b rc_a rc_b out_a out_b marker_sid loser_out
  local both_zero=0 no_winner=0 loser_wrong=0 marker_bad=0 leftover=0 mismatched=0
  out_a="$ST_CWD/writer-a.out"
  out_b="$ST_CWD/writer-b.out"
  i=0
  while [ "$i" -lt "$runs" ]; do
    i=$((i + 1))
    rm -f "$ST_MARKER"
    env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 "$REIN_ST_BASH" "$SCRIPT_PATH" \
      --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-A" \
      --handoff "$ST_HANDOFF" --successor-name "next-a" --note "A's request" \
      >"$out_a" 2>&1 </dev/null &
    pid_a=$!
    env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 "$REIN_ST_BASH" "$SCRIPT_PATH" \
      --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-B" \
      --handoff "$ST_HANDOFF" --successor-name "next-b" --note "B's request" \
      >"$out_b" 2>&1 </dev/null &
    pid_b=$!
    wait "$pid_a"
    rc_a=$?
    wait "$pid_b"
    rc_b=$?
    if [ "$rc_a" -eq 0 ] && [ "$rc_b" -eq 0 ]; then
      both_zero=$((both_zero + 1))
      continue
    fi
    if [ "$rc_a" -ne 0 ] && [ "$rc_b" -ne 0 ]; then
      no_winner=$((no_winner + 1))
      continue
    fi
    # The loser falls through the existing 'there is an unconsumed handover request marker'
    # non-zero path (no new vocabulary added for users).
    if [ "$rc_a" -eq 0 ]; then
      loser_out="$(cat "$out_b")"
      marker_sid="sess-A"
    else
      loser_out="$(cat "$out_a")"
      marker_sid="sess-B"
    fi
    case "$loser_out" in
      *"there is an unconsumed handover request marker"*) ;;
      *) loser_wrong=$((loser_wrong + 1)) ;;
    esac
    # Published artifact non-regression: the marker left behind is always complete JSON and
    # carries the winner's content.
    if ! jq -e . "$ST_MARKER" >/dev/null 2>&1; then
      marker_bad=$((marker_bad + 1))
    elif [ "$(jq -r '.session_id // empty' "$ST_MARKER")" != "$marker_sid" ]; then
      mismatched=$((mismatched + 1))
    fi
    if [ -n "$(find "$ST_RUNTIME" -name "${REIN_MARKER_BASENAME}.*" -print -quit 2>/dev/null)" ]; then
      leftover=$((leftover + 1))
    fi
  done
  if [ "$both_zero" -eq 0 ] && [ "$no_winner" -eq 0 ]; then
    st_ok
  else
    st_fail "only one of two simultaneous requests goes through" \
      "of ${runs} runs: both-0=${both_zero} / both-non-0=${no_winner}"
  fi
  if [ "$loser_wrong" -eq 0 ]; then
    st_ok
  else
    st_fail "the loser fails as an unconsumed handover request" "${loser_wrong} failed with a different reason: $(cat "$out_a") / $(cat "$out_b")"
  fi
  if [ "$marker_bad" -eq 0 ] && [ "$mismatched" -eq 0 ]; then
    st_ok
  else
    st_fail "the remaining marker is the winner's complete JSON" \
      "broken JSON=${marker_bad} / mismatched with the winner=${mismatched}"
  fi
  if [ "$leftover" -eq 0 ]; then
    st_ok
  else
    st_fail "publishing simultaneously leaves no temp file" "${leftover} run(s) left a temp file behind"
  fi
}

# A child process that holds the operation lock and waits (the shape of things while `down` is
# stopping the watcher). Acquires it through **the real entry point** (rein_claim_lock_dir with
# a mode=op declaration) -- a hand-assembled lock has no matching start-time declaration, so it
# gets seized as a 'stale lock with no owner,' and the side meant to wait (publishing a handover
# request) sails through without ever waiting, making the check that's supposed to measure the
# race a no-op.
# Once the stop marker is placed, only releases the lock **if it's still the same generation**
# (a token-checked release).
ST_OP_HOLDER_PID=""
ST_OP_HOLDER_STOP=""
ST_OP_HOLDER_TOKEN="st-op-lock-holder"
st_start_op_lock_holder() {
  local state_dir="$1" runtime_dir="$2" cwd="$3" lock polls=0
  lock="$runtime_dir/$REIN_OP_LOCK_DIRNAME"
  mkdir -p "$state_dir" "$runtime_dir"
  ST_OP_HOLDER_STOP="$state_dir/stop"
  rm -f "$ST_OP_HOLDER_STOP"
  # shellcheck disable=SC2016  # runs in a child shell, so this $ must not be expanded by the caller
  "$REIN_ST_BASH" -c '
. "$1"
rein_claim_lock_dir "$2" \
  start "$(rein_process_start_identity "$$")" \
  cwd "$3" \
  mode "$REIN_LOCK_MODE_OP" \
  token "$5" || exit 1
n=0
while [ ! -f "$4" ] && [ "$n" -lt 200 ]; do n=$((n + 1)); sleep 0.05; done
rein_release_lock_dir_if_mine "$2" "$5"' \
    _ "$SCRIPT_DIR/lib/rein-common.sh" "$lock" "$cwd" "$ST_OP_HOLDER_STOP" \
    "$ST_OP_HOLDER_TOKEN" >/dev/null 2>&1 &
  ST_OP_HOLDER_PID=$!
  while [ "$polls" -lt 200 ] && [ ! -f "$lock/pid" ]; do
    sleep 0.05
    polls=$((polls + 1))
  done
  [ -f "$lock/pid" ]
}

st_stop_op_lock_holder() {
  [ -n "$ST_OP_HOLDER_PID" ] || return 0
  : >"$ST_OP_HOLDER_STOP"
  wait "$ST_OP_HOLDER_PID" 2>/dev/null
  ST_OP_HOLDER_PID=""
}

selftest() {
  local tmp case_dir field mtime epoch_requested resolved default_dir tool notify_count
  local st_records_root st_root_records st_race_pid st_flag
  local st_nr_records st_nr_handoff st_nr_mtime
  local st_section st_missing_section st_extra_section st_fenced_section st_fence
  local st_hint_root st_hint_key st_child_epoch

  tmp="$(mktemp -d "${TMPDIR:-/tmp}/rein-request-selftest.XXXXXX")" || {
    printf '%s: selftest 0 pass / 1 fail\n' "$SCRIPT_NAME"
    return 1
  }
  ST_TMPDIR="$tmp"
  trap st_cleanup EXIT

  # Fixtures are only loaded inside selftest (so production runs never depend on
  # check-only files). Loaded before the first case, since it's what assembles the
  # isolation env for every entry point from here on.
  # shellcheck source-path=SCRIPTDIR
  # shellcheck source=lib/rein-selftest-fixtures.sh
  . "$SCRIPT_DIR/lib/rein-selftest-fixtures.sh"

  # A handover's signals are **removed by the side that places the request**. If the user
  # speaks up in the window between exiting the wait loop and the pointer moving to the
  # successor, a cancellation signal gets placed even though nobody is left to read it -- if
  # it's still there when the same session re-issues the same request, it matches on the first
  # pass of the wait loop and erases the handover, producing a 'cancelled because you spoke up'
  # notification even though the user never spoke up. The declaration 'I want to hand over
  # now' is meant to invalidate past cancellations (placing the cleanup at the entry of the wait
  # loop instead would also throw away a legitimate cancellation placed before the claim).
  case_dir="$tmp/drops-own-marks"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '%s\n' "sess-marks" >"$ST_RUNTIME/$REIN_HANDOVER_READY_BASENAME"
  printf '%s\n' "sess-marks" >"$ST_RUNTIME/$REIN_HANDOVER_CANCEL_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-marks" --handoff "$ST_HANDOFF"
  if st_expect_status "the request still goes through with signals left behind" 0; then
    if [ -e "$ST_RUNTIME/$REIN_HANDOVER_READY_BASENAME" ] ||
      [ -e "$ST_RUNTIME/$REIN_HANDOVER_CANCEL_BASENAME" ]; then
      st_fail "drops its own signals before publishing" "$(ls -a "$ST_RUNTIME")"
    elif [ ! -f "$ST_MARKER" ]; then
      st_fail "places the marker after dropping the signals" "${ST_MARKER} is missing: ${ST_OUT}"
    else
      st_ok
    fi
  fi
  # Never touches another session's signals (only signals it placed itself get removed).
  case_dir="$tmp/keeps-foreign-marks"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '%s\n' "sess-other" >"$ST_RUNTIME/$REIN_HANDOVER_CANCEL_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-mine" --handoff "$ST_HANDOFF"
  if st_expect_status "the request still goes through with another session's signal present" 0; then
    if [ "$(cat "$ST_RUNTIME/$REIN_HANDOVER_CANCEL_BASENAME" 2>/dev/null)" = "sess-other" ]; then
      st_ok
    else
      st_fail "never touches another session's signal" "$(ls -a "$ST_RUNTIME")"
    fi
  fi

  # Running children. A handover replaces this session and its children die with it, so a
  # request placed while one is running is refused outright -- **before this, the request side
  # had no view of children at all** and every case below went through and wrote a marker.
  # (a) One live child: refused non-zero, with the count, the kind, the agent's id, and how long
  #     it has been running, and no marker left behind.
  case_dir="$tmp/child-running"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_CHILDREN_DIRNAME"
  st_child_epoch="$(($(rein_now_epoch) - 30))"
  printf 'Explore\n%s\n%s\n' "$st_child_epoch" "$ST_CWD/records/agent-a1.jsonl" \
    >"$ST_RUNTIME/$REIN_CHILDREN_DIRNAME/sess-kid.a1"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-kid" --handoff "$ST_HANDOFF"
  st_reject_case "refuses while a child is running" 1 "still has 1 running child agent"
  for st_flag in "Explore" "agent a1" "running for "; do
    case "$ST_OUT" in
      *"$st_flag"*) st_ok ;;
      *) st_fail "the refusal names ${st_flag}" "$ST_OUT" ;;
    esac
  done
  # (b) The ledger is partitioned by the parent's session_id: a leftover from another session is
  #     never this session's business (a predecessor stopped externally never delivers
  #     SubagentStop, so leftovers always exist -- reading them would refuse every handover from
  #     here on).
  case_dir="$tmp/child-other-session"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_CHILDREN_DIRNAME"
  printf 'Explore\n%s\n\n' "$(rein_now_epoch)" \
    >"$ST_RUNTIME/$REIN_CHILDREN_DIRNAME/sess-predecessor.a1"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-successor" --handoff "$ST_HANDOFF"
  if st_expect_status "another session's leftover never refuses this session" 0; then
    if [ -f "$ST_MARKER" ]; then
      st_ok
    else
      st_fail "places the marker with only a foreign leftover present" "${ST_MARKER} is missing: ${ST_OUT}"
    fi
  fi
  # (c) An entry whose child has gone quiet past the expiry cutoff isn't counted -- otherwise a
  #     child that vanished without its SubagentStop would refuse that session's handover forever.
  case_dir="$tmp/child-expired"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_CHILDREN_DIRNAME"
  printf 'Explore\n%s\n%s\n' "$(($(rein_now_epoch) - REIN_CHILD_ACTIVE_SEC - 60))" \
    "$ST_CWD/records/agent-a1.jsonl" >"$ST_RUNTIME/$REIN_CHILDREN_DIRNAME/sess-stale.a1"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-stale" --handoff "$ST_HANDOFF"
  if st_expect_status "an expired entry never refuses the handover" 0; then
    if [ -f "$ST_MARKER" ]; then
      st_ok
    else
      st_fail "places the marker once every entry has expired" "${ST_MARKER} is missing: ${ST_OUT}"
    fi
  fi
  # (d) A child registered moments ago whose own record hasn't been created yet still counts --
  #     the moment of registration stands in for the record's mtime, so the window right after
  #     SubagentStart is not a hole.
  case_dir="$tmp/child-no-record-yet"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_CHILDREN_DIRNAME"
  printf 'Plan\n%s\n%s\n' "$(rein_now_epoch)" "$ST_CWD/never-created/agent-a1.jsonl" \
    >"$ST_RUNTIME/$REIN_CHILDREN_DIRNAME/sess-fresh.a1"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-fresh" --handoff "$ST_HANDOFF"
  st_reject_case "a child whose record doesn't exist yet still refuses" 1 "still has 1 running child agent"
  # (e) The other direction: registered long ago, but the record is still being written. The
  #     newer of the two is what the cutoff is measured against, so a long-running child is never
  #     read as expired just because it started a while back.
  case_dir="$tmp/child-long-running"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_CHILDREN_DIRNAME" "$ST_CWD/records"
  : >"$ST_CWD/records/agent-a1.jsonl"
  printf 'Explore\n%s\n%s\n' "$(($(rein_now_epoch) - REIN_CHILD_ACTIVE_SEC - 600))" \
    "$ST_CWD/records/agent-a1.jsonl" >"$ST_RUNTIME/$REIN_CHILDREN_DIRNAME/sess-long.a1"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-long" --handoff "$ST_HANDOFF"
  st_reject_case "a child still writing its record refuses however long it has run" 1 \
    "still has 1 running child agent"
  # (f) A session_id carrying a glob metacharacter. Nothing rejects one (the shape check only
  #     refuses a path separator and whitespace), and the entries are selected by expanding a
  #     glob -- so the id has to stay inside the quotes. Left unquoted, `[1]` would be read as a
  #     pattern and match none of that session's own entries, reopening this hole for exactly
  #     those sessions while every other case here stayed green.
  case_dir="$tmp/child-glob-session-id"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_CHILDREN_DIRNAME"
  printf 'Explore\n%s\n\n' "$(rein_now_epoch)" \
    >"$ST_RUNTIME/$REIN_CHILDREN_DIRNAME/sess[1].a1"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id 'sess[1]' --handoff "$ST_HANDOFF"
  st_reject_case "a session_id with a glob metacharacter still finds its own children" 1 \
    "still has 1 running child agent"

  # The accepting side: exactly one marker matching the contract gets placed.
  case_dir="$tmp/happy"
  st_setup_case "$case_dir"
  touch -t 202001010000 "$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-1" --handoff "$ST_HANDOFF" \
    --successor-name "next-one" --note "12% context usage"
  if st_expect_status "the marker gets written and this ends with 0" 0; then
    if [ ! -f "$ST_MARKER" ]; then
      st_fail "a marker gets placed" "${ST_MARKER} is missing: ${ST_OUT}"
    else
      st_ok
    fi
  fi

  if [ -f "$ST_MARKER" ]; then
    for field in \
      "schema=$REIN_MARKER_SCHEMA" \
      "session_id=sess-1" \
      "handoff_path=$ST_HANDOFF" \
      "cwd=$ST_CWD" \
      "successor_name=next-one" \
      "note=12% context usage"; do
      if [ "$(jq -r ".${field%%=*} // empty" "$ST_MARKER")" = "${field#*=}" ]; then
        st_ok
      else
        st_fail "the marker's ${field%%=*}" "expected ${field#*=} / actual $(jq -r ".${field%%=*} // empty" "$ST_MARKER")"
      fi
    done

    # requested_at must be a format that passes the watcher's R4 (case-prefixed, round-tripped).
    epoch_requested="$(rein_iso_to_epoch "$(jq -r '.requested_at' "$ST_MARKER")")"
    if [ -n "$epoch_requested" ]; then
      st_ok
    else
      st_fail "requested_at passes R4" "cannot be parsed: $(jq -r '.requested_at' "$ST_MARKER")"
    fi

    # R7's ordering guarantee: since the document is touched right before writing, even a 2020
    # mtime falls inside the window.
    mtime="$(rein_mtime "$ST_HANDOFF")"
    if [ -n "$epoch_requested" ] && [ -n "$mtime" ] &&
      [ "$mtime" -le "$((epoch_requested + 60))" ] && [ "$mtime" -ge "$((epoch_requested - 60))" ]; then
      st_ok
    else
      st_fail "touches the document right before writing" "mtime=${mtime} requested_at_epoch=${epoch_requested}"
    fi

    # Checks all the way through atomic write's cleanup (a temp file in the same directory + mv).
    if [ -z "$(find "$ST_RUNTIME" -name "${REIN_MARKER_BASENAME}.*" -print -quit 2>/dev/null)" ]; then
      st_ok
    else
      st_fail "leaves no temp file behind" "$(find "$ST_RUNTIME" -name "${REIN_MARKER_BASENAME}.*")"
    fi
  fi

  # A relative-path document is resolved to an absolute path before being written (the
  # contract requires an absolute path -- R6).
  case_dir="$tmp/relative"
  st_setup_case "$case_dir"
  ST_OUT="$( (cd "$ST_CWD" && env "${ST_ENV_ARGS[@]}" "$REIN_ST_BASH" "$SCRIPT_PATH" \
    --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-rel" --handoff "handoff.md" 2>&1 </dev/null) )"
  ST_STATUS=$?
  if st_expect_status "accepts a relative-path document" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$ST_HANDOFF" ]; then
      st_ok
    else
      st_fail "resolves a relative path to absolute" "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # An optional field's key doesn't appear at all when omitted (an unset value is never
  # recorded as an empty string).
  case_dir="$tmp/minimal"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-2" --handoff "$ST_HANDOFF"
  if st_expect_status "writes fine with no optional fields" 0; then
    if [ "$(jq -r 'has("successor_name"), has("note")' "$ST_MARKER" | tr '\n' ' ')" = "false false " ]; then
      st_ok
    else
      st_fail "omits an omitted optional field entirely" "$(cat "$ST_MARKER")"
    fi
  fi

  # `launch_attempt` (the successor started on that attempt) is **a field the reader writes
  # in after accepting the request**. If the request side wrote it, picking things back up
  # after a run that died mid-launch would set the session the requester claimed as the primary
  # session -- so the writer never writes it, whether or not it was given.
  case_dir="$tmp/no-launch-attempt"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-3" \
    --handoff "$ST_HANDOFF" --successor-name "next-one" --note "12% context usage"
  if st_expect_status "writes fine with every optional field specified" 0; then
    if [ "$(jq -r 'has("launch_attempt")' "$ST_MARKER")" = "false" ]; then
      st_ok
    else
      st_fail "the writer never records the launch declaration" "$(cat "$ST_MARKER")"
    fi
  fi

  # The rejecting side.
  case_dir="$tmp/no-session"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --handoff "$ST_HANDOFF"
  st_reject_case "fails when session_id is missing" 2 "--session-id"

  case_dir="$tmp/space-session"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "a b" --handoff "$ST_HANDOFF"
  st_reject_case "fails when session_id contains whitespace" 2 "whitespace"

  # session_id is an externally sourced string that can expand into a rotated-aside filename.
  # Letting a path separator through would let the reader (the watcher) write outside its own
  # location, or fail to rotate it aside and leave it stuck unconsumed. All three entry points
  # (the hook's stdin, this writer, and the watcher's R3) go through the same one function.
  case_dir="$tmp/path-session"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "a/b" --handoff "$ST_HANDOFF"
  st_reject_case "fails when session_id contains a path separator" 2 "cannot contain a path separator or whitespace"

  # Two requests fired at the same time, with different content. If publishing isn't
  # no-replace, the loser's request disappears with no non-zero exit and no record.
  case_dir="$tmp/two-writer"
  st_setup_case "$case_dir"
  st_two_writer_barrier_case 10

  # The default document (next to the records) takes effect when neither --handoff nor config
  # is given. Checks by whether the file actually placed there lands in the marker, that
  # default resolution isn't assembled separately per entry point (it goes through one
  # shared-library function).
  case_dir="$tmp/handoff-default"
  st_setup_case "$case_dir"
  mkdir -p "$ST_CWD/$REIN_RECORDS_DIRNAME"
  rein_st_write_handoff "$ST_CWD/$REIN_RECORDS_DIRNAME/$REIN_HANDOFF_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-default"
  if st_expect_status "writes fine with the default document" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$ST_CWD/$REIN_RECORDS_DIRNAME/$REIN_HANDOFF_BASENAME" ]; then
      st_ok
    else
      st_fail "puts the default document into the marker" "$(cat "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # For a lineage relocated with `--root`, the default follows the root side (tracking the
  # records location). Even if a document sits at the cwd side's `.rein/`, it's never grabbed
  # from there (never letting two lineages read the same document).
  case_dir="$tmp/handoff-default-root"
  st_setup_case "$case_dir"
  mkdir -p "$ST_CWD/$REIN_RECORDS_DIRNAME"
  rein_st_write_handoff "$ST_CWD/$REIN_RECORDS_DIRNAME/$REIN_HANDOFF_BASENAME"
  st_records_root="$ST_CWD/root/$REIN_ROOT_RECORDS_RELDIR"
  st_root_records="$st_records_root/$(rein_cwd_key "$ST_CWD")"
  mkdir -p "$st_root_records"
  rein_st_write_handoff "$st_root_records/$REIN_HANDOFF_BASENAME"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" "REIN_RECORDS_ROOT=$st_records_root" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-root" 2>&1 </dev/null)"
  ST_STATUS=$?
  if st_expect_status "writes fine at the default even for a --root lineage" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$st_root_records/$REIN_HANDOFF_BASENAME" ]; then
      st_ok
    else
      st_fail "the --root default tracks the records on the root side" "$(cat "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # If the default document doesn't exist yet, this fails instead of writing (fail-loud --
  # never creates a handover request with no document).
  case_dir="$tmp/handoff-default-missing"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-3"
  st_reject_case "fails if the default document doesn't exist" 1 "$ST_CWD/$REIN_RECORDS_DIRNAME/$REIN_HANDOFF_BASENAME"

  # A lineage that explicitly emptied it out in config fails as 'the path could not be
  # determined' instead of guessing its way back to the default.
  case_dir="$tmp/handoff-disabled"
  st_setup_case "$case_dir"
  printf 'handoff_path=\n' >"$ST_USER_CONFIG"
  # The empty value is placed at the **user layer** (`config unset`'s default scope is
  # project, so hinting at the default scope wouldn't actually clear it even after running the
  # hint exactly as given -- placing it at this layer is what makes that wrong hint cause real
  # harm).
  mkdir -p "$ST_CWD/$REIN_RECORDS_DIRNAME"
  rein_st_write_handoff "$ST_CWD/$REIN_RECORDS_DIRNAME/$REIN_HANDOFF_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-4"
  st_reject_case "fails without falling back to the default when it's explicitly empty" 2 "handoff_path"
  # The hint line fills in effective values for **both the lineage and the scope**, checked by
  # exact match (a partial match would let a line that dropped the scope pass on a matching
  # prefix).
  st_expect_hint_line_after "$ST_HINT_LEAD_HANDOFF" "names the emptied-out layer explicitly in the hint line" \
    "$(rein_shell_quote "$REIN_BIN") --config $(rein_shell_quote "$ST_USER_CONFIG") --cwd $(rein_shell_quote "$ST_CWD") config unset --user handoff_path"
  st_expect_no_bare_hint "never hints a line with the scope dropped" "config unset" " --user"
  # **Hint -> run -> re-diagnose.** Matching text alone can't measure whether the line actually
  # runs and works, so this cuts the hint out of the output, runs it as-is, and checks all the
  # way through to whether the value actually cleared (the same request now goes through).
  st_run_hint_line "the hint line can be run as-is" "$ST_HINT_LEAD_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-4b"
  if st_expect_status "running the hint clears the explicit empty and the request goes through" 0; then
    if [ -f "$ST_MARKER" ]; then
      st_ok
    else
      st_fail "can write a handover request after running the hint" "${ST_OUT}"
    fi
  fi

  # config's handoff_path stands in for --handoff (decision 3's "a configurable value").
  case_dir="$tmp/handoff-from-config"
  st_setup_case "$case_dir"
  printf 'handoff_path=%s\n' "$ST_HANDOFF" >"$ST_USER_CONFIG"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-cfg"
  if st_expect_status "writes fine with config's handoff_path" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$ST_HANDOFF" ]; then
      st_ok
    else
      st_fail "puts config's handoff_path into the marker" "$(cat "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # --handoff is stronger than config (lets a different document be passed for each run).
  case_dir="$tmp/handoff-cli-wins"
  st_setup_case "$case_dir"
  rein_st_write_handoff "$ST_CWD/other-handoff.md"
  printf 'handoff_path=%s\n' "$ST_CWD/other-handoff.md" >"$ST_USER_CONFIG"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-cli" --handoff "$ST_HANDOFF"
  if st_expect_status "writes fine with both --handoff and config present" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$ST_HANDOFF" ]; then
      st_ok
    else
      st_fail "--handoff takes priority over config's handoff_path" "$(cat "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # The runtime directory self-declares its owner (cwd), so leftover runtime data can be
  # traced back to its owner from outside.
  case_dir="$tmp/owner"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-owner" --handoff "$ST_HANDOFF"
  if st_expect_status "writes fine with an owner" 0; then
    if [ "$(cat "$ST_RUNTIME/$REIN_OWNER_BASENAME" 2>/dev/null)" = "$ST_CWD" ]; then
      st_ok
    else
      st_fail "places an owner in the runtime directory" "$(cat "$ST_RUNTIME/$REIN_OWNER_BASENAME" 2>/dev/null)"
    fi
  fi

  # Never writes to a runtime directory owned by a different cwd (never silently carries on
  # after mixing lineages up).
  case_dir="$tmp/owner-mismatch"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '/somewhere/else\n' >"$ST_RUNTIME/$REIN_OWNER_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-owner2" --handoff "$ST_HANDOFF"
  st_reject_case "fails on a runtime directory with a different owner" 1 "belongs to a different target"

  # An owner file that isn't a regular file, isn't exactly one line, or is a symlink is never
  # let through the check (letting it through would write a handover request into a runtime
  # directory with no valid owner).
  case_dir="$tmp/owner-directory"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME/$REIN_OWNER_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-owner3" --handoff "$ST_HANDOFF"
  st_reject_case "fails on a directory as the owner" 1 "is not a regular file"

  case_dir="$tmp/owner-multiline"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '%s\n/somewhere/else\n' "$ST_CWD" >"$ST_RUNTIME/$REIN_OWNER_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-owner4" --handoff "$ST_HANDOFF"
  st_reject_case "fails on a multi-line owner" 1 "is not exactly one line"

  case_dir="$tmp/owner-symlink"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '%s\n' "$ST_CWD" >"$ST_CWD/owner-target"
  ln -s "$ST_CWD/owner-target" "$ST_RUNTIME/$REIN_OWNER_BASENAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-owner5" --handoff "$ST_HANDOFF"
  st_reject_case "fails on a symlink owner" 1 "is a symlink"

  # The side that loses the race to create the owner file goes through the same full
  # verification as before creation. Accepting a mere `head -1` match would let a symlink
  # dropped into the race window, or a multi-line file whose first line just happens to match,
  # be accepted as the owner. The losing side's state -- already sitting there right before the
  # write -- is built directly and called that way (triggering the race itself from outside
  # doesn't produce a deterministic result).
  case_dir="$tmp/claim-race"
  st_setup_case "$case_dir"
  printf '%s\n' "$ST_CWD" >"$ST_CWD/race-target"
  mkdir -p "$ST_RUNTIME/loser-symlink"
  ln -s "$ST_CWD/race-target" "$ST_RUNTIME/loser-symlink/$REIN_OWNER_BASENAME"
  if rein_claim_runtime_owner "$ST_RUNTIME/loser-symlink" "$ST_CWD"; then
    st_fail "never accepts a symlink owner dropped in by a race" "accepted it"
  else
    case "$REIN_RUNTIME_ERROR" in
      *"is a symlink"*)
        st_ok
        ;;
      *)
        st_fail "the reason for a symlink dropped in by a race" "${REIN_RUNTIME_ERROR}"
        ;;
    esac
  fi

  mkdir -p "$ST_RUNTIME/loser-multiline"
  printf '%s\n/somewhere/else\n' "$ST_CWD" >"$ST_RUNTIME/loser-multiline/$REIN_OWNER_BASENAME"
  if rein_claim_runtime_owner "$ST_RUNTIME/loser-multiline" "$ST_CWD"; then
    st_fail "never accepts a multi-line owner dropped in by a race" "accepted a form matching only on the first line"
  else
    case "$REIN_RUNTIME_ERROR" in
      *"is not exactly one line"*)
        st_ok
        ;;
      *)
        st_fail "the reason for a multi-line file dropped in by a race" "${REIN_RUNTIME_ERROR}"
        ;;
    esac
  fi

  mkdir -p "$ST_RUNTIME/loser-other-cwd"
  printf '/somewhere/else\n' >"$ST_RUNTIME/loser-other-cwd/$REIN_OWNER_BASENAME"
  if rein_claim_runtime_owner "$ST_RUNTIME/loser-other-cwd" "$ST_CWD"; then
    st_fail "never accepts a different-cwd owner dropped in by a race" "accepted it"
  else
    case "$REIN_RUNTIME_ERROR" in
      *"belongs to a different target"*)
        st_ok
        ;;
      *)
        st_fail "the reason for a different cwd dropped in by a race" "${REIN_RUNTIME_ERROR}"
        ;;
    esac
  fi

  # The accepting side: with nobody having placed one, it can claim ownership itself (checking
  # the verification isn't so broad it also rejects its own creation).
  mkdir -p "$ST_RUNTIME/claim-free"
  if rein_claim_runtime_owner "$ST_RUNTIME/claim-free" "$ST_CWD" &&
    [ "$(cat "$ST_RUNTIME/claim-free/$REIN_OWNER_BASENAME" 2>/dev/null)" = "$ST_CWD" ]; then
    st_ok
  else
    st_fail "can claim ownership when nobody has placed one" \
      "owner=$(cat "$ST_RUNTIME/claim-free/$REIN_OWNER_BASENAME" 2>/dev/null) reason=${REIN_RUNTIME_ERROR}"
  fi

  # A request that landed on the wrong lineage fails with 'wrong owner.' If the unconsumed-
  # marker check ran first, it would look to the user as if an old request was stuck on their
  # own lineage, steering them toward the SKILL-forbidden move of deleting the existing marker.
  case_dir="$tmp/owner-mismatch-with-marker"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '/somewhere/else\n' >"$ST_RUNTIME/$REIN_OWNER_BASENAME"
  printf '{"schema":"rein.handover-request.v1"}\n' >"$ST_MARKER"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-owner6" --handoff "$ST_HANDOFF"
  if st_expect_status "a mismatched location fails with the owner reason" 1; then
    case "$ST_OUT" in
      *"belongs to a different target"*)
        st_ok
        ;;
      *)
        st_fail "never turns a mismatch into the unconsumed-marker reason" "${ST_OUT}"
        ;;
    esac
  fi

  # An explicit empty CLI flag is never silently folded into unset (the one way to disable it
  # stays config unset).
  case_dir="$tmp/empty-opts"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-empty" --handoff ""
  # For a key with a default, `unset` **brings the default back** -- so the way to hint at
  # disabling it is the explicit-empty form (`config set handoff_path ""`), not the reverse.
  # Hinting the reverse would leave a user who meant to disable it running on the default
  # document anyway.
  st_reject_case "an empty --handoff fails, naming the disable path per layer" 2 'config set --user handoff_path ""'
  case "$ST_OUT" in
    *"config unset --user handoff_path or config unset --project handoff_path"*) st_ok ;;
    *) st_fail "also hints the way back to the default" "${ST_OUT}" ;;
  esac
  st_run_request --cwd "$ST_CWD" --runtime-dir "" --session-id "sess-empty" --handoff "$ST_HANDOFF"
  st_reject_case "fails on an empty --runtime-dir" 2 "config unset --user runtime_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-empty" --handoff
  st_reject_case "fails on --handoff with no value" 2 "--handoff requires a value"

  # The same discipline applies to a flag that has no config key too. Silently falling
  # through to a failed `shift 2` on a missing value would end non-zero **without printing a
  # single line of reason** -- a handover request is one line the primary session fires
  # automatically, so a silent non-zero leaves 'why it couldn't be placed' unobservable to
  # anyone, and no handover happens (skills/request/SKILL.md promises 'the reason goes to
  # stderr').
  case_dir="$tmp/missing-values"
  st_setup_case "$case_dir"
  for st_flag in --cwd --session-id --successor-name --note; do
    st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --handoff "$ST_HANDOFF" \
      --session-id "sess-noval" "$st_flag"
    st_reject_case "fails on ${st_flag} with no value and gives a reason" 2 "${st_flag} requires a value"
  done
  # An explicit empty value isn't folded into unset either (`--cwd ""` grabs the shell's own
  # current lineage instead of the intended target, and `--note ""` silently drops a note the
  # caller meant to write -- both would otherwise pass through as a different input with no
  # signal at all).
  for st_flag in --cwd --session-id --successor-name --note; do
    st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --handoff "$ST_HANDOFF" \
      --session-id "sess-emptyval" "$st_flag" ""
    st_reject_case "never folds an empty ${st_flag} into unset" 2 "${st_flag} cannot take an empty value"
  done
  # The accepting side (a flag with a value still lands as before). Looking only at the
  # rejecting side, the check would be too broad to tell apart from a form that accepts no
  # optional field at all.
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --handoff "$ST_HANDOFF" \
    --session-id "sess-values" --successor-name "next-values" --note "a note here"
  if st_expect_status "a flag with a value is still accepted as before" 0; then
    if [ "$(jq -r '.successor_name + "/" + .note' "$ST_MARKER" 2>/dev/null)" = "next-values/a note here" ]; then
      st_ok
    else
      st_fail "puts an optional field with a value into the marker" "$(cat "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # Isolation counter-proof (both sides): a launch that isn't given the isolation entry point
  # does end up reading the user's own config -- the hole is real. A launch routed through
  # the isolation env doesn't read it. Measuring only one side can't be told apart from
  # 'wiring that was never read in the first place.'
  case_dir="$tmp/ambient-config"
  st_setup_case "$case_dir"
  mkdir -p "$ST_CWD/ambient/rein"
  printf 'unknown_key=1\n' >"$ST_CWD/ambient/rein/config"
  ST_OUT="$(env -u REIN_CONFIG_FILE XDG_CONFIG_HOME="$ST_CWD/ambient" \
    XDG_STATE_HOME="$ST_CWD/xdg-state" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-ambient" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  ST_STATUS=$?
  st_reject_case "reads the outer config when not given the isolation entry point" 1 "unknown key"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" XDG_CONFIG_HOME="$ST_CWD/ambient" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-ambient" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  ST_STATUS=$?
  if st_expect_status "doesn't read the outer config with the isolation env" 0; then
    if [ -f "$ST_MARKER" ]; then
      st_ok
    else
      st_fail "reads only the isolated config" "${ST_OUT}"
    fi
  fi

  # A malformed config also fails on the writer's side (never silently falls back to the
  # default).
  case_dir="$tmp/broken-config"
  st_setup_case "$case_dir"
  printf 'unknown_key=1\n' >"$ST_USER_CONFIG"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-bad" --handoff "$ST_HANDOFF"
  st_reject_case "fails on an unknown key in config" 1 "unknown key"

  # config's runtime_dir decides where runtime data is kept (the path that never passes
  # --runtime-dir).
  case_dir="$tmp/runtime-from-config"
  st_setup_case "$case_dir"
  printf 'runtime_dir=%s\n' "$ST_CWD/from-config" >"$ST_USER_CONFIG"
  rein_st_start_fake_watcher "$ST_CWD/from-config" "$ST_CWD"
  st_run_request --cwd "$ST_CWD" --session-id "sess-rt" --handoff "$ST_HANDOFF"
  if st_expect_status "writes fine with config's runtime_dir" 0; then
    if [ -f "$ST_CWD/from-config/$REIN_MARKER_BASENAME" ] &&
      [ ! -e "$ST_CWD/xdg-state/rein" ]; then
      st_ok
    else
      st_fail "places the marker at config's runtime_dir" "$(find "$ST_CWD" -name "$REIN_MARKER_BASENAME")"
    fi
  fi

  case_dir="$tmp/absent-handoff"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-4" --handoff "$ST_CWD/absent.md"
  st_reject_case "fails on a document that doesn't exist" 1 "does not exist"

  case_dir="$tmp/empty-handoff"
  st_setup_case "$case_dir"
  : >"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-5" --handoff "$ST_HANDOFF"
  st_reject_case "fails on an empty document" 1 "is empty"

  # Acceptance conditions are 'a regular file, not a symlink, non-empty,' checked through the
  # one function shared with a cold start (`rein init`'s template) and launching the first
  # session (bootstrap). If the stricter side rejected a shape the looser side let through (a
  # directory, a symlink), a lineage could end up where the first session starts fine but only
  # handovers ever get stuck.
  case_dir="$tmp/dir-handoff"
  st_setup_case "$case_dir"
  rm -f "$ST_HANDOFF"
  mkdir -p "$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-dir" --handoff "$ST_HANDOFF"
  st_reject_case "never accepts a directory as the document" 1 "is not a regular file"

  # A symlink is rejected because swapping out what it points at could substitute a different
  # file's existence, emptiness, and freshness for the checks. Even a target that would itself
  # be acceptable still fails.
  case_dir="$tmp/symlink-handoff"
  st_setup_case "$case_dir"
  printf 'the real document\n' >"$ST_CWD/real.md"
  rm -f "$ST_HANDOFF"
  ln -s "$ST_CWD/real.md" "$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-link" --handoff "$ST_HANDOFF"
  st_reject_case "never accepts a symlink as the document" 1 "symlink"

  # The accepting side (a regular file through the same path still writes). Looking only at
  # the rejecting side, acceptance would be too broad to tell apart from a form that accepts nothing
  # at all.
  case_dir="$tmp/regular-handoff"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-regular" --handoff "$ST_HANDOFF"
  if st_expect_status "writes fine with a regular-file document" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$ST_HANDOFF" ]; then
      st_ok
    else
      st_fail "puts that document into the marker" "$(cat "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  # Section-structure checking (a layer only a handover request enforces). **The list of
  # sections is canonical in the shared library's ordering**, and the check builds its input
  # from that same ordering -- copying section names out here by hand would leave the check
  # holding stale text the moment the ordering changes.
  #
  # The missing side: doesn't write if even one of the template's sections is gone. The reason
  # names **the missing heading itself** (a single line saying "the section structure is wrong"
  # would leave no way to know what to fix right before a handover).
  case_dir="$tmp/handoff-missing-section"
  st_setup_case "$case_dir"
  st_missing_section="${REIN_HANDOFF_SECTIONS[${#REIN_HANDOFF_SECTIONS[@]} - 1]}"
  {
    printf '# Handoff document\n'
    for st_section in "${REIN_HANDOFF_SECTIONS[@]}"; do
      [ "$st_section" = "$st_missing_section" ] && continue
      printf '\n## %s\n\n(check fixture)\n' "$st_section"
    done
  } >"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-missing-section" --handoff "$ST_HANDOFF"
  st_reject_case "fails on a document missing a section" 1 "missing headings: \"## ${st_missing_section}\""

  # The added side: doesn't write if a `##` heading not in the template got added. **This
  # direction is the one that actually matters** -- an added section gets copied forward at
  # every handover, so once it's added it never goes away without someone removing it by hand.
  # The reason names the extra heading (without naming what to remove, the writer would have to
  # suspect everything).
  case_dir="$tmp/handoff-extra-section"
  st_setup_case "$case_dir"
  st_extra_section="Work Log"
  rein_st_write_handoff "$ST_HANDOFF"
  printf '\n## %s\n\n(a section not in the template)\n' "$st_extra_section" >>"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-extra-section" --handoff "$ST_HANDOFF"
  st_reject_case "fails on a document with a heading added that's not in the template" 1 "headings not in the template: \"## ${st_extra_section}\""
  st_expect_contains "points to where permanent rules belong" "write them to whatever your environment designates as canonical instead"

  # **Inside and outside a code fence.** A `##` inside a fence is never counted, and a `##`
  # **after a closing fence is counted** -- measuring only the accepting side by adding a fence
  # block to the input would let the fence check flip to 'once open, never close again' and
  # still leave every case green (every heading after it becomes invisible, silently letting
  # through a section added at the end -- the very accident this mechanism is supposed to
  # prevent goes dead for **the most ordinary shape of document**, one with a pasted command or
  # log). One failing case closes both the start and the end of the fence.
  case_dir="$tmp/handoff-fenced-heading"
  st_setup_case "$case_dir"
  rein_st_write_handoff "$ST_HANDOFF"
  st_extra_section="Work Log"
  st_fenced_section="Pasted Log Heading"
  st_fence='```'
  printf '\n%s\n## %s\n%s\n\n## %s\n\n(a section not in the template)\n' \
    "$st_fence" "$st_fenced_section" "$st_fence" "$st_extra_section" >>"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-fenced-heading" --handoff "$ST_HANDOFF"
  st_reject_case "counts a heading after a closing fence" 1 "headings not in the template: \"## ${st_extra_section}\""
  st_expect_not_contains "never counts a heading inside a fence" "$st_fenced_section"

  # A 3-run fence marker inside a 4-run fence doesn't close it (only the same kind at the same
  # length or longer closes it). Loosen this and inside and outside swap places -- **every
  # heading that actually exists in the file goes uncounted and the whole thing gets labeled
  # 'missing'** -- a handover stalls on a reason nobody can act on by reading it.
  case_dir="$tmp/handoff-nested-fence"
  st_setup_case "$case_dir"
  rein_st_write_handoff "$ST_HANDOFF"
  printf '\n%s\n%s\n## %s\n%s\n\n## %s\n' \
    '````' "$st_fence" "$st_fenced_section" '````' "$st_extra_section" >>"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-nested-fence" --handoff "$ST_HANDOFF"
  st_reject_case "a 3-run fence inside a 4-run fence doesn't close it" 1 "headings not in the template: \"## ${st_extra_section}\""
  st_expect_not_contains "swapped inside/outside never calls a real section missing" "missing headings: "

  # An indented closing fence still closes it. Without that, everything after it becomes
  # 'inside a fence,' the same 'names a real heading as missing' shape as above.
  case_dir="$tmp/handoff-indented-fence"
  st_setup_case "$case_dir"
  rein_st_write_handoff "$ST_HANDOFF"
  printf '\n  %s\n## %s\n  %s\n\n## %s\n' \
    "$st_fence" "$st_fenced_section" "$st_fence" "$st_extra_section" >>"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-indented-fence" --handoff "$ST_HANDOFF"
  st_reject_case "an indented closing fence still closes it" 1 "headings not in the template: \"## ${st_extra_section}\""
  st_expect_not_contains "treating indentation as never-closed never calls a real section missing" "missing headings: "

  # An unclosed fence fails with **its own reason, kept separate from 'missing'**. Mixing it
  # into 'missing' would tell the writer to 'add' headings that already exist in the file -- a
  # reason that reading it still can't fix.
  case_dir="$tmp/handoff-unclosed-fence"
  st_setup_case "$case_dir"
  rein_st_write_handoff "$ST_HANDOFF"
  printf '\n%s\n## %s\n' "$st_fence" "$st_fenced_section" >>"$ST_HANDOFF"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-unclosed-fence" --handoff "$ST_HANDOFF"
  st_reject_case "fails on an unclosed fence" 1 "is never closed"
  st_expect_not_contains "never turns an unclosed fence into the missing-section reason" "missing headings: "

  case_dir="$tmp/bad-cwd"
  st_setup_case "$case_dir"
  st_run_request --cwd "$ST_CWD/absent" --runtime-dir "$ST_RUNTIME" --session-id "sess-6" --handoff "$ST_HANDOFF"
  st_reject_case "fails when the target directory doesn't exist" 2 "the target directory"

  # A directory that exists but can't be resolved (no permission to cd into it). Skipping the
  # resolution-failure check would carry an empty cwd forward, turn the reason into something
  # unrelated (the watcher being undecidable, the runtime directory's owner), and leak bash's
  # raw error line into user-facing output -- leaving the user chasing an unrelated watcher
  # lock.
  case_dir="$tmp/unresolvable-cwd"
  st_setup_case "$case_dir"
  mkdir -p "$ST_CWD/nox"
  chmod 000 "$ST_CWD/nox"
  st_run_request --cwd "$ST_CWD/nox" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-nox" --handoff "$ST_HANDOFF"
  # An unreadable directory can't be removed along with the rest of the check's temp area, so
  # this is restored before judging.
  chmod 755 "$ST_CWD/nox"
  st_reject_case "fails on a target directory that can't be resolved" 2 "cannot resolve the target directory"
  st_expect_not_contains "never leaks a raw shell error into user-facing output" ": cd: "
  st_expect_not_contains "never turns a resolution failure into a watcher-side reason" "watcher"

  # Silently overwriting an unconsumed marker would make the earlier request disappear with
  # no record.
  case_dir="$tmp/existing"
  st_setup_case "$case_dir"
  mkdir -p "$ST_RUNTIME"
  printf '{"schema":"rein.handover-request.v1"}\n' >"$ST_MARKER"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-7" --handoff "$ST_HANDOFF"
  if st_expect_status "never overwrites an unconsumed marker" 1; then
    if [ "$(jq -r '.session_id // empty' "$ST_MARKER")" = "" ]; then
      st_ok
    else
      st_fail "never overwrites an unconsumed marker" "got overwritten: $(cat "$ST_MARKER")"
    fi
  fi

  # Never writes to a location with no watcher (if the marker were left with nobody there to
  # remove it, every request after it would be rejected as 'unconsumed' forever, and the
  # handover gate would stay closed for that lineage). The rejecting side is checked on non-zero,
  # the reason, and no marker, plus the GUI notification's destination and body, verbatim
  # ('notified something' would still pass even with a garbled destination).
  rein_st_write_fake_bin "$tmp/bin"
  case_dir="$tmp/watcher-absent"
  st_setup_case "$case_dir"
  rein_st_stop_fake_watcher "$ST_RUNTIME"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" \
    PATH="$tmp/bin:$PATH" \
    FAKE_LOG="$tmp/claude-args.log" \
    FAKE_NOTIFY_LOG="$tmp/watcher-notify.log" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  ST_STATUS=$?
  st_reject_case "never writes a handover request with no watcher present" 1 "the watcher is not running"
  # For a lineage with an explicit location (here, --runtime-dir), flatly saying
  # `rein --cwd <cwd> up` would be a wrong hint -- it would start a different watcher looking at
  # the default location. **The line that can actually be run has the lineage named right into
  # it.** Adding a prose aside like 'add the same option' still leaves a hole, because it makes
  # the user go look the effective value up themselves.
  case "$ST_OUT" in
    *"$ST_RUNTIME"*)
      st_ok
      ;;
    *)
      st_fail "names the explicit location in the hint" "${ST_OUT}"
      ;;
  esac
  # Cuts out the one line of hint and checks it by **exact match**. A partial match would let
  # a flat claim that dropped the naming through on nothing more than a matching prefix.
  st_expect_hint_line "hints a line with the lineage named" \
    "$(rein_shell_quote "$REIN_BIN") --cwd '${ST_CWD}' up --runtime-dir '${ST_RUNTIME}'"
  # A form with the naming dropped is a wrong hint. **Looks right after every occurrence** --
  # checking only the end of the line would let a bare form mixed into prose (text the user
  # could plausibly paste) slip through even with a correct hint line elsewhere.
  # The needle **doesn't include the command name**, because what's dangerous is simply 'text
  # with the verb but no lineage named' -- whether it's written `rein` or `'rein'`, the user
  # can paste either as the same one line.
  st_expect_no_bare_hint "never hints a line with the lineage dropped" \
    "--cwd '${ST_CWD}' up" " --runtime-dir "
  notify_count="$(rein_st_calls_total "$tmp/watcher-notify.log")"
  if [ "$notify_count" -eq 1 ]; then
    st_ok
  else
    st_fail "the notification for a missing watcher is exactly 1" "count=${notify_count}"
  fi
  if [ "$(rein_st_notify_field "$tmp/watcher-notify.log" "$notify_count" title)" = "rein: cannot write the handover request" ]; then
    case "$(rein_st_notify_field "$tmp/watcher-notify.log" "$notify_count" message)" in
      *"the watcher is not running"*)
        st_ok
        ;;
      *)
        st_fail "the missing-watcher notification body" "$(rein_st_notify_field "$tmp/watcher-notify.log" "$notify_count" message)"
        ;;
    esac
  else
    st_fail "the missing-watcher notification title" "$(rein_st_notify_field "$tmp/watcher-notify.log" "$notify_count" title)"
  fi

  # The accepting side (the same input, the same location -- still writes as before when the
  # watcher is running). Looking only at the rejecting side, the judgment would be too broad to
  # tell apart from a form that never lets anything through.
  rein_st_start_fake_watcher "$ST_RUNTIME" "$ST_CWD"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher" --handoff "$ST_HANDOFF"
  if st_expect_status "writes fine with the same input when the watcher is running" 0; then
    if [ -f "$ST_MARKER" ]; then
      st_ok
    else
      st_fail "places the marker when the watcher is running" "${ST_OUT}"
    fi
  fi

  # **If checking residency and publishing aren't inside the same exclusive region, a run that
  # races `down` writes to a location with no watcher and returns 0** (the requester believes
  # it landed and stays quiet, but nobody is there to pick it up). `down` takes the same
  # operation lock before stopping the watcher, so this reproduces that shape by 'holding the
  # lock while taking the watcher down, then releasing the lock afterward.' If the judgment sat
  # only outside the exclusive region, the request would carry a stale 'it's there' forward
  # through the wait for the lock and go straight to publishing.
  case_dir="$tmp/watcher-down-race"
  st_setup_case "$case_dir"
  if st_start_op_lock_holder "$ST_CWD/op-holder" "$ST_RUNTIME" "$ST_CWD"; then
    env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 "$REIN_ST_BASH" "$SCRIPT_PATH" \
      --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" --session-id "sess-race" \
      --handoff "$ST_HANDOFF" >"$ST_CWD/race.out" 2>&1 </dev/null &
    st_race_pid=$!
    # The operation lock is held, so the request waits here (5 seconds by default). While it
    # waits, the watcher is taken down -- the shape where residency disappears after the check
    # and before publishing.
    sleep 1
    rein_st_stop_fake_watcher "$ST_RUNTIME"
    st_stop_op_lock_holder
    wait "$st_race_pid"
    ST_STATUS=$?
    ST_OUT="$(cat "$ST_CWD/race.out")"
    st_reject_case "doesn't place it if the watcher went down right before publishing" 1 "the watcher is not running"
  else
    st_fail "can start a child holding the operation lock" "the watcher lock was never published: ${ST_RUNTIME}"
  fi

  # For a lineage with no explicit location (the default XDG state area), the line that runs
  # can be stated flat out. The difference from an explicit lineage can only be measured here
  # (if both read the same text, one of them is necessarily a wrong hint).
  case_dir="$tmp/watcher-absent-default"
  st_setup_case "$case_dir"
  rein_st_stop_fake_watcher "$ST_RUNTIME"
  st_run_request --cwd "$ST_CWD" --session-id "sess-watcher-def" --handoff "$ST_HANDOFF"
  if st_expect_status "fails on a missing watcher at the default location too" 1; then
    st_expect_hint_line "hints a command line that runs for the default lineage" \
      "$(rein_shell_quote "$REIN_BIN") --cwd '${ST_CWD}' up"
    if [ -z "$(find "$ST_CWD" -name "$REIN_MARKER_BASENAME" -print -quit 2>/dev/null)" ]; then
      st_ok
    else
      st_fail "never writes a marker at the default location either" "$(find "$ST_CWD" -name "$REIN_MARKER_BASENAME")"
    fi
  fi

  # **The hint for a lineage relocated to a root (`--root`).** This one can't be named through
  # `--runtime-dir` (the records location would fall back to the default `<cwd>/.rein/`, and
  # checking the handover request would read a different lineage's pointer) -- the line emitted
  # must carry `--root`. Pinned by exact match.
  case_dir="$tmp/watcher-absent-root"
  st_setup_case "$case_dir"
  st_hint_root="$ST_CWD/root"
  st_hint_key="$(rein_cwd_key "$ST_CWD")"
  ST_RUNTIME="$st_hint_root/$REIN_ROOT_STATE_RELDIR/$st_hint_key"
  ST_MARKER="$ST_RUNTIME/$REIN_MARKER_BASENAME"
  mkdir -p "$ST_RUNTIME" "$st_hint_root/$REIN_ROOT_RECORDS_RELDIR/$st_hint_key"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 \
    "REIN_RECORDS_ROOT=$st_hint_root/$REIN_ROOT_RECORDS_RELDIR" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher-root" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  ST_STATUS=$?
  if st_expect_status "fails on a missing watcher for a root-relocated lineage too" 1; then
    st_expect_hint_line "a root-relocated lineage carries the root in its hint" \
      "$(rein_shell_quote "$REIN_BIN") --root '${st_hint_root}' --cwd '${ST_CWD}' up"
    # A form that fell back to `--runtime-dir` would be a wrong hint (the records location
    # falls back to the default) -- checks all the way through to it never being emitted.
    case "$ST_OUT" in
      *"--runtime-dir"*)
        st_fail "never falls back to the --runtime-dir form for a root-relocated lineage" "${ST_OUT}"
        ;;
      *)
        st_ok
        ;;
    esac
  fi

  # A form where the records location can't be resolved (the location is a symlink). Falling
  # back to the default `--runtime-dir` form with no material to judge from would start
  # **a watcher looking at a different location** for a root-relocated lineage -- say 'cannot
  # tell' when it can't be told (never silently falls back to the default).
  case_dir="$tmp/watcher-absent-norecords"
  st_setup_case "$case_dir"
  rein_st_stop_fake_watcher "$ST_RUNTIME"
  mkdir -p "$ST_CWD/records-elsewhere"
  ln -s "$ST_CWD/records-elsewhere" "$ST_CWD/$REIN_RECORDS_DIRNAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher-norec" --handoff "$ST_HANDOFF"
  if st_expect_status "fails even when the records location can't be resolved" 1; then
    case "$ST_OUT" in
      *"cannot be named explicitly"*)
        st_ok
        ;;
      *)
        st_fail "gives a reason for why it can't be named" "${ST_OUT}"
        ;;
    esac
    st_expect_no_bare_hint "never emits a flat-claim line when it can't be named" \
      "--cwd '${ST_CWD}' up" " --runtime-dir "
  fi

  # Undecidable (the watcher lock is there but its owner can't be read) is never flattened into
  # a flat 'not running.' Falling back to the start-it hint would either start a second watcher
  # on a lineage that's actually already being watched, or leave a state that starting it
  # doesn't actually resolve.
  case_dir="$tmp/watcher-undecidable"
  st_setup_case "$case_dir"
  rein_st_stop_fake_watcher "$ST_RUNTIME"
  mkdir -p "$ST_RUNTIME/$REIN_LOCK_DIRNAME"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher3" --handoff "$ST_HANDOFF"
  st_reject_case "fails as undecidable on a lock whose owner can't be read" 1 "cannot tell whether the watcher is running"
  case "$ST_OUT" in
    *"$ST_RUNTIME/$REIN_LOCK_DIRNAME"*)
      st_ok
      ;;
    *)
      st_fail "points at where the watcher lock is" "${ST_OUT}"
      ;;
  esac
  case "$ST_OUT" in
    *"the watcher is not running,"*)
      st_fail "never turns undecidable into the not-running wording" "${ST_OUT}"
      ;;
    *)
      st_ok
      ;;
  esac

  # Even with the watcher lock's owner alive, if the binary itself isn't the watcher for this
  # location (a PID reuse), that's **the not-running side** -- hint how to start it. Falling
  # back to the undecidable side would split it from the claiming side's categorization (the
  # watcher reclaims that lock through the same cross-check), stopping a state that starting it
  # exactly as hinted would resolve with a 'go check' instead.
  case_dir="$tmp/watcher-pid-reuse"
  st_setup_case "$case_dir"
  rein_st_stop_fake_watcher "$ST_RUNTIME"
  mkdir -p "$ST_RUNTIME/$REIN_LOCK_DIRNAME"
  # The check process's own pid (alive, but not the watcher watching this location).
  printf '%s\n' "$$" >"$ST_RUNTIME/$REIN_LOCK_DIRNAME/pid"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher4" --handoff "$ST_HANDOFF"
  st_reject_case "a lock with a reused PID fails on the not-running side" 1 "the watcher is not running"
  case "$ST_OUT" in
    *"stale lock"*)
      st_ok
      ;;
    *)
      st_fail "gives a reason naming it a stale lock" "${ST_OUT}"
      ;;
  esac
  case "$ST_OUT" in
    *"cannot tell whether the watcher is running"*)
      st_fail "never turns it into the undecidable wording" "${ST_OUT}"
      ;;
    *)
      st_ok
      ;;
  esac

  # A form where a missing watcher overlaps with an old marker. If the reason turned into
  # 'unconsumed,' the user would never see the root cause and get steered toward the
  # contract-violating move of deleting the existing marker.
  case_dir="$tmp/watcher-absent-with-marker"
  st_setup_case "$case_dir"
  rein_st_stop_fake_watcher "$ST_RUNTIME"
  printf '{"schema":"rein.handover-request.v1"}\n' >"$ST_MARKER"
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-watcher2" --handoff "$ST_HANDOFF"
  if st_expect_status "fails even with an old marker still sitting there" 1; then
    case "$ST_OUT" in
      *"the watcher is not running"*)
        st_ok
        ;;
      *)
        st_fail "never turns a missing watcher into the unconsumed reason" "${ST_OUT}"
        ;;
    esac
  fi

  # The default for runtime data is the user's own state area (XDG), not under the project.
  default_dir="$(XDG_STATE_HOME="$tmp/xdg" rein_resolve_runtime_dir "$tmp/happy")"
  case "$default_dir" in
    "$tmp/xdg/rein/happy-"*)
      st_ok
      ;;
    *)
      st_fail "the default for runtime data is under XDG" "resolved to: ${default_dir}"
      ;;
  esac
  resolved="$(XDG_STATE_HOME="$tmp/xdg" rein_resolve_runtime_dir "$tmp/happy" "$tmp/explicit")"
  if [ "$resolved" = "$tmp/explicit" ]; then
    st_ok
  else
    st_fail "an explicit effective value takes priority over the default" "resolved to: ${resolved}"
  fi
  # The environment-variable entry point lives in the config layer (REIN_RUNTIME_DIR is the
  # environment layer for the runtime_dir key). The resolution function itself never reads the
  # environment -- so the entry point never splits into two.
  resolved="$(XDG_STATE_HOME="$tmp/xdg" REIN_RUNTIME_DIR="$tmp/env-runtime" rein_resolve_runtime_dir "$tmp/happy")"
  case "$resolved" in
    "$tmp/xdg/rein/happy-"*)
      st_ok
      ;;
    *)
      st_fail "the resolution function never reads the environment variable directly" "resolved to: ${resolved}"
      ;;
  esac
  # REIN_RUNTIME_DIR as an environment layer takes effect on the execution path (the entry
  # point the contract calls out as relocatable).
  case_dir="$tmp/runtime-from-env"
  st_setup_case "$case_dir"
  rein_st_start_fake_watcher "$ST_CWD/from-env" "$ST_CWD"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" REIN_RUNTIME_DIR="$ST_CWD/from-env" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --session-id "sess-env" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  ST_STATUS=$?
  if st_expect_status "writes fine at the REIN_RUNTIME_DIR location" 0; then
    if [ -f "$ST_CWD/from-env/$REIN_MARKER_BASENAME" ]; then
      st_ok
    else
      st_fail "REIN_RUNTIME_DIR decides where runtime data is kept" "$(find "$ST_CWD" -name "$REIN_MARKER_BASENAME")"
    fi
  fi

  # A CLI flag is stronger than an environment variable (counter-proof of priority).
  case_dir="$tmp/runtime-cli-wins"
  st_setup_case "$case_dir"
  ST_OUT="$(env "${ST_ENV_ARGS[@]}" REIN_RUNTIME_DIR="$ST_CWD/from-env" \
    "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-cli-rt" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  ST_STATUS=$?
  if st_expect_status "writes fine with both --runtime-dir and the environment variable present" 0; then
    if [ -f "$ST_MARKER" ] && [ ! -e "$ST_CWD/from-env" ]; then
      st_ok
    else
      st_fail "--runtime-dir takes priority over REIN_RUNTIME_DIR" "$(find "$ST_CWD" -name "$REIN_MARKER_BASENAME")"
    fi
  fi

  # The gate for a location that must never be touched (where isolation would break). **Both
  # sides** are pinned with fixtures before using the predicate -- since every launch this
  # check makes sits outside the never-touch root, looking only at the side that doesn't trip
  # it would show the same green whether the judgment is always false or has been deleted
  # altogether. The root passed is a temp directory, so both sides are measured without touching
  # a single byte of real state.
  case_dir="$tmp/never-root"
  st_setup_case "$case_dir"
  # Also measures a document placed at the records location (the default handoff_path sits
  # next to the records).
  st_nr_records="$ST_CWD/$REIN_RECORDS_DIRNAME"
  st_nr_handoff="$st_nr_records/$REIN_HANDOFF_BASENAME"
  mkdir -p "$st_nr_records"
  rein_st_write_handoff "$st_nr_handoff"
  touch -t 202001010000 "$st_nr_handoff"
  st_nr_mtime="$(rein_mtime "$st_nr_handoff")"
  ST_ENV_ARGS=("${REIN_ST_ENV_ARGS[@]}" "${REIN_SELFTEST_NEVER_ROOTS_ENV_NAME}=$tmp/never-root-unrelated")
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-nr-pass" --handoff "$st_nr_handoff"
  if st_expect_status "a launch that resolved locations outside the never-touch root sails through" 0; then
    if [ -f "$ST_MARKER" ]; then
      st_ok
    else
      st_fail "a launch that sailed through writes a marker" "${ST_MARKER} is missing: ${ST_OUT}"
    fi
  fi
  # (1) The runtime-directory branch. Both the marker and the operation lock live under it, so
  # tripping it must not let even one of them get created.
  case_dir="$tmp/never-root-runtime"
  st_setup_case "$case_dir"
  ST_ENV_ARGS=("${REIN_ST_ENV_ARGS[@]}" "${REIN_SELFTEST_NEVER_ROOTS_ENV_NAME}=$ST_RUNTIME")
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-nr-runtime" --handoff "$ST_HANDOFF"
  st_reject_case "fails a launch that resolved the runtime directory under the never-touch root" 1 \
    "${ST_RUNTIME} (never-touch root ${ST_RUNTIME})"
  if [ ! -e "$ST_RUNTIME/$REIN_OP_LOCK_DIRNAME" ]; then
    st_ok
  else
    st_fail "the rejecting side writes not even one file under the never-touch root" "an operation lock got created: ${ST_RUNTIME}/${REIN_OP_LOCK_DIRNAME}"
  fi
  # (2) The handoff-document branch. Since the runtime directory sits outside the never-touch
  # root, this would pass if the document weren't checked too -- and passing means the touch
  # right before publishing moves the user's real document's mtime (material for R7's
  # ordering judgment).
  case_dir="$tmp/never-root-handoff"
  st_setup_case "$case_dir"
  st_nr_records="$ST_CWD/$REIN_RECORDS_DIRNAME"
  st_nr_handoff="$st_nr_records/$REIN_HANDOFF_BASENAME"
  mkdir -p "$st_nr_records"
  rein_st_write_handoff "$st_nr_handoff"
  touch -t 202001010000 "$st_nr_handoff"
  st_nr_mtime="$(rein_mtime "$st_nr_handoff")"
  ST_ENV_ARGS=("${REIN_ST_ENV_ARGS[@]}" "${REIN_SELFTEST_NEVER_ROOTS_ENV_NAME}=$st_nr_records")
  st_run_request --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-nr-handoff" --handoff "$st_nr_handoff"
  st_reject_case "fails a launch that resolved the handoff document under the never-touch root" 1 \
    "${st_nr_handoff} (never-touch root ${st_nr_records})"
  if [ "$(rein_mtime "$st_nr_handoff")" = "$st_nr_mtime" ]; then
    st_ok
  else
    st_fail "the rejecting side never touches a document under the never-touch root" \
      "the mtime moved: ${st_nr_mtime} -> $(rein_mtime "$st_nr_handoff")"
  fi

  # In an environment where a prerequisite tool doesn't work, this would end up placing an
  # out-of-contract time format or broken JSON, and the watcher would reject it with the wrong
  # reason ('JSON is broken'). Fail on the writer's side first instead.
  # A fake osascript so a real GUI notification never fires (the production notification path
  # still runs as-is).
  rein_st_write_fake_bin "$tmp/bin"
  for tool in jq date stat perl; do
    case_dir="$tmp/missing-$tool"
    st_setup_case "$case_dir"
    rein_st_write_broken_tool "$tmp/broken-$tool" "$tool"
    ST_OUT="$(env "${ST_ENV_ARGS[@]}" \
      PATH="$tmp/broken-$tool:$tmp/bin:$PATH" \
      FAKE_LOG="$tmp/claude-args.log" \
      FAKE_NOTIFY_LOG="$tmp/notify.log" \
      "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
      --session-id "sess-tool" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
    ST_STATUS=$?
    st_reject_case "fails when the prerequisite tool ${tool} doesn't work" 2 "prerequisite tool"
    # The notification is checked verbatim, all the way to the destination (title) and the
    # reason ('notified something' would still pass even with a garbled destination).
    notify_count="$(rein_st_calls_total "$tmp/notify.log")"
    if [ "$(rein_st_notify_field "$tmp/notify.log" "$notify_count" title)" = "rein: cannot write the handover request" ]; then
      case "$(rein_st_notify_field "$tmp/notify.log" "$notify_count" message)" in
        *"a prerequisite tool is not usable"*)
          st_ok
          ;;
        *)
          st_fail "the ${tool} prerequisite notification body" "$(rein_st_notify_field "$tmp/notify.log" "$notify_count" message)"
          ;;
      esac
    else
      st_fail "the ${tool} prerequisite notification title" "$(rein_st_notify_field "$tmp/notify.log" "$notify_count" title)"
    fi
  done

  # Printing usage is also an execution path (bash 3.2 crashes when multibyte text follows a
  # variable expansion immediately).
  st_run_request --help
  if st_expect_status "prints usage with --help" 0; then
    case "$ST_OUT" in
      *"usage:"*)
        st_ok
        ;;
      *)
        st_fail "prints usage with --help" "usage isn't shown: ${ST_OUT}"
        ;;
    esac
  fi
  st_run_request --bogus
  if st_expect_status "rejects an unknown argument" 2; then
    case "$ST_OUT" in
      *"usage:"*)
        st_ok
        ;;
      *)
        st_fail "rejects an unknown argument" "usage isn't shown: ${ST_OUT}"
        ;;
    esac
  fi

  # Where the bundled library lives is never left to an external command's output.

  # Sets up the attack exactly as it would happen: places a `dirname` that returns empty at
  # the front of PATH, and launches with the cwd set to a directory rigged with a trap
  # `lib/rein-common.sh`. When the location is decided by an external command's output, moving
  # to an empty string **succeeds without changing the working directory**, so the current
  # location comes back as the launching cwd, and the trap runs **in this very process**
  # (observed: this shape ended with the trap's own exit code, 78). Whether what gets loaded is
  # the bundled copy is measured by splitting on the trap's exit code.
  local hijack_out hijack_rc
  case_dir="$tmp/lib-path-hijack"
  st_setup_case "$case_dir"
  mkdir -p "$ST_CWD/hijack-bin" "$ST_CWD/lib"
  printf '#!/bin/sh\nprintf ""\n' >"$ST_CWD/hijack-bin/dirname"
  chmod +x "$ST_CWD/hijack-bin/dirname"
  printf 'exit 78\n' >"$ST_CWD/lib/rein-common.sh"
  hijack_out="$(cd "$ST_CWD" && env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 \
    PATH="$ST_CWD/hijack-bin:$PATH" "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" \
    --runtime-dir "$ST_RUNTIME" --session-id "sess-hijack" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  hijack_rc=$?
  rm -rf "${ST_CWD:?}/lib" "${ST_CWD:?}/hijack-bin"
  if [ "$hijack_rc" -eq 78 ]; then
    st_fail "never loads a same-named library from the cwd side" "the trap ran (rc=78): ${hijack_out}"
  else
    st_ok
  fi

  # A relative-path launch is **a legitimate path** (run from inside the repository) -- never
  # rejected. Dropping the cwd prefix would leave the location stuck as the literal word
  # `rein-request.sh`, unable to load the bundled library, and fail -- these two cases catch
  # that regression. Measures **both** the no-slash form (`bash rein-request.sh`) and the
  # relative form from the repo root (`bash scripts/rein-request.sh`) -- since the prefixing is
  # implemented through cutting on `%/*`, a form with a path separator and one without can come
  # out differently.
  case_dir="$tmp/relative-launch-bare"
  st_setup_case "$case_dir"
  hijack_out="$(cd "$SCRIPT_DIR" && env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 \
    "$REIN_ST_BASH" "$SCRIPT_NAME" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-rel-bare" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  hijack_rc=$?
  if [ "$hijack_rc" -eq 0 ] && [ -f "$ST_MARKER" ]; then
    st_ok
  else
    st_fail "can still load the bundled library on a no-slash relative launch" \
      "exit=${hijack_rc}: ${hijack_out}"
  fi

  case_dir="$tmp/relative-launch-nested"
  st_setup_case "$case_dir"
  hijack_out="$(cd "${SCRIPT_DIR%/*}" && env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 \
    "$REIN_ST_BASH" "${SCRIPT_DIR##*/}/$SCRIPT_NAME" --cwd "$ST_CWD" --runtime-dir "$ST_RUNTIME" \
    --session-id "sess-rel-nested" --handoff "$ST_HANDOFF" 2>&1 </dev/null)"
  hijack_rc=$?
  if [ "$hijack_rc" -eq 0 ] && [ -f "$ST_MARKER" ]; then
    st_ok
  else
    st_fail "can still load the bundled library on a relative launch from the repo root" \
      "exit=${hijack_rc}: ${hijack_out}"
  fi

  # Resolving the handoff document's path is never left to an external command's output either.

  # This doesn't reach arbitrary code execution, but the way it fails is the same shape as
  # above: cutting the parent out from an external command's output means that whenever it
  # returns empty, the parent collapses to the launching cwd, and
  # `--handoff nested/handoff.md` **silently grabs a different `./handoff.md`** than what was
  # specified (not one line of signal, exit code stays 0). `st_setup_case` already places
  # `$ST_CWD/handoff.md`, so the decoy is sitting there from the start -- specify the nested
  # one, and whichever document lands in the marker tells the two apart. This splits **by the
  # path's literal text**, because splitting by content would make 'grabbed a different file'
  # and 'failed to resolve' look like the same FAIL.
  #
  # The fake `dirname` returns empty **only for this one specified path** -- every other call
  # answers for itself. Returning empty across the board would fail the path that writes the
  # marker (the shared library's swap-write goes through `mkdir -p "$(dirname ...)"`) first and
  # **never reach the site meant to be measured** -- that failure comes with a reason and a
  # non-zero, so it isn't the silent-grab shape, but from this check's point of view both sides
  # look like the same non-zero and can't be told apart. Widening this to return empty
  # everywhere is something to do only once the remaining `dirname` calls are closed off.
  case_dir="$tmp/handoff-path-hijack"
  st_setup_case "$case_dir"
  mkdir -p "$ST_CWD/hijack-bin" "$ST_CWD/nested"
  cat >"$ST_CWD/hijack-bin/dirname" <<'HIJACK'
#!/bin/sh
case "$1" in
  */nested/handoff.md) printf '\n' ;;
  /*/*) printf '%s\n' "${1%/*}" ;;
  /*) printf '/\n' ;;
  */*) printf '%s\n' "${1%/*}" ;;
  *) printf '.\n' ;;
esac
HIJACK
  chmod +x "$ST_CWD/hijack-bin/dirname"
  rein_st_write_handoff "$ST_CWD/nested/handoff.md"
  ST_OUT="$(cd "$ST_CWD" && env "${ST_ENV_ARGS[@]}" REIN_NOTIFY_SILENT=1 \
    PATH="$ST_CWD/hijack-bin:$PATH" "$REIN_ST_BASH" "$SCRIPT_PATH" --cwd "$ST_CWD" \
    --runtime-dir "$ST_RUNTIME" --session-id "sess-handoff-hijack" \
    --handoff "nested/handoff.md" 2>&1 </dev/null)"
  ST_STATUS=$?
  rm -rf "${ST_CWD:?}/hijack-bin"
  if st_expect_status "grabs the specified handoff document even with decoys sitting there" 0; then
    if [ "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)" = "$ST_CWD/nested/handoff.md" ]; then
      st_ok
    else
      st_fail "grabs the specified handoff document even with decoys sitting there" \
        "$(jq -r '.handoff_path' "$ST_MARKER" 2>/dev/null)"
    fi
  fi

  printf '%s: selftest %d pass / %d fail\n' "$SCRIPT_NAME" "$st_pass_count" "$st_fail_count"
  [ "$st_fail_count" -eq 0 ]
}

main() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --selftest)
        selftest # test-side-scope-exempt: the one line that starts the selftest entry point (not a production writer)
        return $?
        ;;
      --cwd)
        need_value "--cwd" $# "${2:-}" || return 2
        TARGET_CWD="$2"
        shift 2
        ;;
      --runtime-dir)
        check_opt "--runtime-dir" runtime_dir $# "${2:-}" || return 2
        RUNTIME_DIR_OPT="$2"
        shift 2
        ;;
      --session-id)
        need_value "--session-id" $# "${2:-}" || return 2
        SESSION_ID="$2"
        shift 2
        ;;
      --handoff)
        check_opt "--handoff" handoff_path $# "${2:-}" || return 2
        HANDOFF_OPT="$2"
        shift 2
        ;;
      --successor-name)
        need_value "--successor-name" $# "${2:-}" || return 2
        SUCCESSOR_NAME="$2"
        shift 2
        ;;
      --note)
        need_value "--note" $# "${2:-}" || return 2
        NOTE="$2"
        shift 2
        ;;
      -h | --help)
        usage
        return 0
        ;;
      *)
        printf '%s: unknown argument: %s\n' "$SCRIPT_NAME" "$1" >&2
        usage >&2
        return 2
        ;;
    esac
  done
  run_request
}

main "$@"
